      SUBROUTINE AIRBRS
C
C     H. G. NORMENT, ATMOSPHERIC SCIENCE ASSOCIATES - DECEMBER 1978
C
C
C     COMBINES FUNCTIONS OF SUBROUTINES TIME, TEMP, MASS, AND VAPOR
C FOR AN AIRBURST. ALSO SETS LOGNCRMAL DEBRIS PARTICLE SIZE
C     DISTRIBUTION PARAMETERS FOR AN AIRBURST.   A GEOMETRIC STANDARD
C     DEVIATION OF 2.0 IS ASSUMED.   THE MEDIAN PARTICLE DIAMETER WAS
C     COMPUTED FROM EQS. (43) AND (44) OF NATHANS,ET AL., JGR75, 7565
C     (1971) (FOR BROWNIAN MOTION)
C
C
      COMMON /BASIC/ W,FW,ZBRSTZ,HEIGHT,ZSCL,SLDTMP,TMSD,XGZ,YGZ,TGZ
      COMMON /CONTRL/ DETID(12),IC(20),IRAD,IRISE,ISIN,ISOUT,JPARN,KDI
      COMMON /INITL/ F, PHI, SSAM, TME, TMPG, TMPS, VPR
      COMMON /PARTCL/ NDSTR,RHOP,DMEAN,SD,PS(200),DIAM(201),FMASS(200)
C
C
C     SET TIME OF THE SECOND THERMAL MAXIMUM AND THE DELFIC INITIAL
C     TIME (SEC)
C
      T2M = 0.045 * W**(0.42)
      TME = 56. * T2M * W**(-0.30)
C
C     SET INITIAL CLOUD TEMPERATURE
C
      A = 6847. * W**(-0.0131)
      B = -0.4473 * W**(0.0436)
      TMPG = A * (TME / T2M)**B + 1500.
      TMPS = TMPG
C
C SET MASS OF CONDENSEC PHASE MATERIAL IN THE CLOLC (KG)
      SSAM = 90.718
      VPR = 0.0
      IF(IC(1) .NE. 0  .OR.  DMEAN .NE. 0.0) RETURN
C
C     SET DE9RIS PARTICLE SIZE DISTRIBUTION PARAMETERS
C
      SD = 2.0
      DMEAN = 0.15
      RETURN
      END
CDECK,DSTBN
      SUBROUTINE DSTBN
C
C     H. G. NORMENT, ATMOSPHERIC SCIENCE ASSOCIATES - DECEMBER 1978
C
C
C     SETS UP HISTOGRAM TABLES OF  PARTICLE MASS AS A FUNCTION OF
C     PARTICLE DIAMETER.
C
C     LOGNORMAL DISTRIBUTION TO 100
C     POWER FUNCTION DISTRIBUTION TO 200
C     TABULAR DISTRIBUTION TO 300
C
C     EQUATION 26.2.23 OF NBS-AMS 55 HANDBOOK IS USED TO COMPUTE THE
C     PROBABILITY FUNCTION ARGUMENT FROM THE RATIONAL POLYNOMIAL
C     APPROXIMATION TO THE NORMAL PROBABILITY FUNCTION.
C
C.
      COMMON /CONTRL/ DETID(12),IC(20),IRAD,IRISE,ISIN,ISOUT,JPARN,KDI
      COMMON /INITL/ F, PHI, SSAM, TME, TMPG, TMPS, VPR
      COMMON /PARTCL/ NDSTR,RHOP,DMEAN,SD,PS(200),DIAM(201),FMASS(200)
      EQUIVALENCE (DMEAN,CAYM),(SD,EXPO)
      DATA PROGRM, PI/ 6HDSTBN , 3.141592654/
C
C
      TA(X)=SQRT(ALOG(1.0/X**2))
      APX(X)=TA(X)-(2.515517+0.802853*TA(X)+0.010328*TA(X)**2)/
     1(1.0+1.432788*TA(X)+0.189269*TA(X)**2+0.001308*TA(X)**3)
C
      LD=NDSTR+1
      IF(IC(1)-1)100,200,300
  100 IF(DMEAN)111,111,112
  111 DMEAN=0.407
      SD=4.0
  112 IF(NDSTR-1)101,101,102
  101 PS(1)=DMEAN*1.0E-6
      C5=SD**5
      DIAM(1)=DMEAN*C5*1.0E-6
      DIAM(2)=DMEAN/C5*1.0E-6
      FMASS(1)=1.0
      GO TO 400
  102 BARMU=ALOG(DMEAN)
      SIGMA=ALOG(SD)
      BARMU=BARMU+3.*SIGMA**2
      FRAC=1.0/FLOAT(NDSTR)
      DO 103 ND=1,NDSTR
  103 FMASS(ND)=FRAC
      NH=NDSTR/2
      DO 104 I=1,NH
      PRB=FLOAT(I)*FRAC
      DIAM(I+1)=BARMU+APX(PRB)*SIGMA
      J=NDSTR-I+1
  104 DIAM(J)=BARMU-APX(PRB)*SIGMA
C
C     FOR THE 2 EXTREME INTERVALS THE AVERAGE DIAMETER IS
C     ASSUMED TO BE AT HALF A MASS FRACTION FROM ZERO AND ONE
C
      PRB=FRAC/2.0
      PS(1)=BARMU+APX(PRB)*SIGMA
      PS(NDSTR)=BARMU-APX(PRB)*SIGMA
      DIAM(1)=2.*PS(1)-DIAM(2)
      DIAM(LD)=2.*PS(NDSTR)-DIAM(NDSTR)
C
C     CALCULATE MEAN DIAMETERS FROM BOUNDARY VALUES
C
      J=NDSTR-1
      IF(J-1)107,107,105
  105 DO 106 I=2,J
  106 PS(I)=0.5*(DIAM(I)+DIAM(I+1))
  107 DO 108 I=1,NDSTR
      DIAM(I)=EXP(DIAM(I)) *1.0E-6
  108 PS(I)=EXP(PS(I))*1.0E-6
      DIAM(LD)=EXP(DIAM(LD)) *1.0E-6
      GO TO 400
  200 IF(EXPO .GE. 4.0) CALL ERROR(PROGRM, -200, ISOUT)
      AN=FLOAT(NDSTR)
      FRAC=1.0/AN
      DO 205 I=1,NDSTR
  205 FMASS(I)=FRAC
      POW=1.0/(4.0-EXPO)
      DMIN = (6.0*FRAC/(PI*RHOP*CAYM*POW))**POW
      DO 206 IJ=1,NDSTR
      AJ=IJ-1
  206 DIAM(IJ)=(AN-AJ)**POW*DMIN
      PS(NDSTR)=DMIN*0.5**POW
      DIAM(LD)=PS(NDSTR)**2/DIAM(NDSTR)
      ND=NDSTR-1
      DO 207 IJ=1,ND
  207 PS(IJ)=SQRT(DIAM(IJ)*DIAM(IJ+1))
      GO TO 400
  300 DO 301 I=1,NDSTR
  301 PS(I)=SQRT(DIAM(I)*DIAM(I+1))*1.0E-6
      DO 308 IJ=1,LD
  308 DIAM(IJ)=1.0E-6*DIAM(IJ)
  400 RETURN
      END
