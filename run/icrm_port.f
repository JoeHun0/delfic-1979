CDECK,CRM
      SUBROUTINE CRM
C
C     H. G. NORMENT, ATMOSPHERIC SCIENCE ASSOCIATES - DECEMBER 1976
C
C
C     COMPUTE THE DYNAMIC CLOUD RISE
C
C     THIS CODE CLOSELY FELLOWS THAT OF HUEBSCH, *THE DEVELOPMENT OF A
C     WATER-SURFACE-BURST FALLOUT MODEL - THE RISE AND EXPANSION OF THE
C ATOMIC CLOUD . USNRCL-TR-74 . (23 APRIL 1964) , ANC TURMULENCE ,
C     TORIOIAL CIRCULATION AND DISPERSION OF FALLOUT FROM THE RISING
C     NUCLEAR CLOUD*, USNRDL-TR1054 (5 AUGUST 1966).  THE HUEBSCH MODEL
C     HAS BEEN MODIFIED AS DESCRIBED BY NORMENT, *VALIDATION AND
C     REFINEMENT OF THE DELFIC CLOUD RISE MODULE', DNA 4320F(15JAN1977)
C
C
      COMMON /CLOUD/ CHANGE,CMLR  ,C2    ,C3    ,C6    ,DEK    ,DRM    ,
     1 DS    ,DST   ,DST0  ,DST1  ,DST2  ,DT    ,DU    ,DWT    ,DX     ,
     2 DZ    ,ED    ,EK    ,EPS   ,ES    ,HLR   ,KS    ,KSV    ,MWYA   ,
     3 N     ,NNN   ,P     ,PW    ,R     ,RA    ,RL    ,RM     ,RZT    ,
     4 S     ,SAVE  ,SHAPE ,SMALLT,T     ,TE    ,U     ,V      ,WT     ,
     5 X     ,XE    ,Z     ,ZBFR  ,ZLMT  ,SPARE
      COMMON /CONTRL/ DETID(12),IC(20),IRAD,IRISE,ISIN,ISOUT,JPARN,KDI
      COMMON /PARTCL/ NDSTR,RHOP,DMEAN,SD,PS(200),DIAM(201),FMASS(200)
      COMMON /TABLES/ MCX, CX(50,10), GDPST(10,100)
C
      DIMENSION Y(200)
      EQUIVALENCE (Y(1),GDPST(1,1))
C
C
C     COMPUTE THE PARTIAL PRESSURE OF THE WATER VAPOR IN THE CLOUD
C
   35 PW=P*X*29./(18.+29.*X)
C
C     COMPUTE SATURATION WATER VAPOR PRESSURE AND CLOUD AIR MASS
C
      ES=611.*(T/273.)**(-5.13)*EXP((25.*(T-273.))/T)
      RA=RM/V*(1.+X)/(1.+X+S+WT)
C
C     WET OR DRY EQUATIONS
C
      GO TO (150,1531,1531),N
  150 IF(ES-PW)152,152,1531
C
C     STORE VARIABLES(KSV=1) OR RESTART AT PREVIOUS TIME STEP (KSV=2)
C
  152 KSV=2
 1532 CALL RSTR
    9 VTEMPY=V
C
C     INTEGRATE
C
      CALL RKGILL
C
C         ADJUST IN-CLOUD PARTICLE CONCENTRATIONS TO BE CONSISTENT WITH
C     CLOUD VOLUME CHANGE
C
      DO 86 J=1,NDSTR
   86 Y(J)=Y(J)*VTEMPY/V
C
C     ACCUMULATE CLOUD TIME
C
      SMALLT=SMALLT+DST
C
C     TEST FOR TIME STEP CHANGE
      IF(ABS(SMALLT-1.0).LT.0.001)GO TO 87
      IF(SMALLT-1.0)8,87,88
   87 DST=DST1
   88 R=SQRT(3.*V/(RZT*12.5663706E0))
      GO TO 35
C
C     COMPUTE PARTICLE FALLOUT RATE
C
 1531 CALL CPFR
      GO TO (901,901,8),MWYA
  901 IF(IC(6) .NE. 0) CALL DBG
      CALL DCSN
    8 CALL CXPN
      GO TO (724,724,148),MWYA
  724 KSV=1
      GO TO 1532
  148 CALL CRMW
      RETURN
      END
CDECK,CRMINT
      SUBROUTINE CRMINT
C
C     H. G. NORMENT, ATMOSPHERIC SCIENCE ASSOCIATES - DECEMBER 1978
C
C
C     INITIALIZE CLOUD AND PARTICLE VARIABLES FOR THE DYNAMIC CLOUD RISE
C
C
       COMMON /ATMOS/ NAT, ALT(256),  ATP(256),  PRS(256), RLH(256),
     1        RHO(256), ETA(256), NHODO, ZV(100),  VX(100), VY(100)
      COMMON /BASIC/ W,FW,ZBRSTZ,HEIGHT,ZSCL,SLDTMP,TMSD,XGZ,YGZ,TGZ
      COMMON /CLOUD/ CHANGE,CMLR  ,C2    ,C3    ,C6    ,DEK    ,DRM    ,
     1 DS    ,DST   ,DST0  ,DST1  ,DST2  ,DT    ,DU    ,DWT    ,DX     ,
     2 DZ    ,ED    ,EK    ,EPS   ,ES    ,HLR   ,KS    ,KSV    ,MWYA   ,
     3 N     ,NNN   ,P     ,PW    ,R     ,RA    ,RL    ,RM     ,RZT    ,
     4 S     ,SAVE  ,SHAPE ,SMALLT,T     ,TE    ,U     ,V      ,WT     ,
     5 X     ,XE    ,Z     ,ZBFR  ,ZLMT  ,SPARE
      COMMON /INITL/ F, PHI, SSAM, TME, TMPG, TMPS, VPR
      COMMON /PARTCL/ NDSTR,RHOP,DMEAN,SD,PS(200),DIAM(201),FMASS(200)
      COMMON /TABLES/ MCX, CX(50,10), GDPST(10,100)
C
      DIMENSION Y(200),CG(200)
      EQUIVALENCE (Y(1),GDPST(1,1)), (CG(1),GDPST(1,21))
C
C
      CHANGE=100.
      CMLR=0.
      SMALLT=0.
      WT=0.
      N=1
      MWYA=1
      KS = 0
      DST0 = .03125
      DST1 = 0.25
      DST2 = 2.5
      DST=DST0
      SSAM=SSAM+VPR
C     COMPUTE TURBULENCE CRAG PARAMETER
C
      C2 = AMAX1( 0.004, AMIN1( 0.100, 0.1 * W**(-0.3333333333) ))
C     SET TURBULENT ENERGY DISSIPATION PARAMETER
C
      C3=0.175
      C6=1.0
C
      T=TMPG
C
C     COMPUTE CLOUD CENTER HEIGHT, VOLUME, RADII, INITIAL MIXING RATIOS
C
      Z=HEIGHT+ZBRSTZ+ 90.*W**0.3333333333
      CALL TRPL(Z,NAT ,ALT,ATP,TE)
      CALL TRPL(Z,NAT ,ALT,PRS,P)
      CALL TRPL(Z,NAT ,ALT,RLH,HLR)
      XE=109.98*HLR*(TE/273.)**(-5.13)*EXP((25.*(TE-273.))/TE)/(P*29.)
C
      TAD=0.
      IF(TMPS-848.)5,5,6
    5 TPR=TMPS
      GO TO 7
    6 TPR=848.
      TAD=1003.8*(TMPS-TPR)+0.06755*(TMPS**2-TPR**2)
    7 SOILHT=SSAM*(TAD+781.6*(TPR-TE)+0.2856*(TPR**2-TE**2)+
     11.881E+7*(1./TPR-1./TE))
      TAD=0.
      TPR=T
      IF(TPR-2300.)17,17,16
   16 TAD= -3587.5*(TPR-2300.) + 1.0625*(TPR**2-(2300.)**2)
      TPR=2300.
   17 FQ=4.18E12*F*W-SOILHT
      RMAO=PHI*FQ/(TAD+946.6*(TPR-TE)+0.09855*(TPR**2-TE**2)+XE*(1697.66
     1 *(T-TE) +0.572087*(T**2-TE**2)))
      RMWO=FQ*(1.-PHI)/(1697.66*(T-TE)+0.572087*(T**2-TE**2)+2.5E6)
     1  +RMAO*XE
      X=RMWO/RMAO
      RM=RMAO+RMWO+SSAM
      S=SSAM/RMAO
      V=(RMAO+RMWO)*287.*T*(1.+29.*X/18.)/(P*(1.+X))
      R=0.
C SET SHAPE SO THAT THE CLOUD IS AN OBLATE ELLIPSOID WITH
C     ECCENTRICITY=0.75     COMPUTE HORIZONTAL AND VERTICAL CLOUD RADII
      SHAPE = 0.66144
C
      IF(V.GT.0.0) R=(3.*V/(12.5663706* SHAPE ))**(1.0/3.0)
      RZT= SHAPE *R
C     COMPUTE INITIAL RISE VELOCITY
C
      U=1.2*SQRT(9.8*R)
C     OMPUTEI NI TIAL TURBULENT KINETIC ENERGY DENSITY
C
      EK=0.5*U**2
C     COMPUTE INITIAL TURBULENT ENERGY LOSS RATE
C
      EPS=C3*(2.*EK)**1.5/RZT
C     COMPUTE ENTRAINMENT PARAMETER
C
      RL = AMAX1( AMAX1( 0.12, 0.1 * W**0.1 ), 0.01*W**0.3333333333 )
C
C     COMPUTE INITIAL IN-CLOUD PARTICLE CONCENTRATIONS
C
      Q=S/(1.0+X+S)*RM/(V*RHOP*0.5235988)
      DO 801 J=1,NDSTR
      Y(J)=FMASS(J)*Q/PS(J)**3
  801 CG(J)=0.
C     UPPER LIMIT FOR Z TO PREVENT PROGRAM RUNAWAY
C
      ZLMT=10000.0*W**0.25 + HEIGHT + ZBRSTZ
      RETURN
      END
