  903 FORMAT (1H1//////////
     1  20X30HNEGATIVE PARTICLE DENSITY                          /////)
  758 FORMAT(1H124X73H* * * * * * * * * * * * * * * * * * * * * * * * *
     1* * * * * * * * * * * *//  22X, 76HPARTICLE SETTLING RATES ARE INA
     2CCURATE.  DAVIES NUMBER IS TOO LARGE FOR THE I3, 8H TH SIZE// 24X,
