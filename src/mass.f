      SUBROUTINE HASS
C
C     H. G. NORMENT, ATMOSPHERIC SCIENCE ASSOCIATES - DECEMBER 1978
C
C
C     ESTIMATES  MASS OF FALLOUT IN THE FIREBALL FOR A SURFACE, LOW
C     AIRBURST OR SHALLOW SUBSURFACE BURST.
C
C
      COMMON /BASIC/ W,FH,ZBRSTZ,HEIGHT,ZSCL,SLOTMP,TMSO,XGZ,YGZ,TGZ
      COMMON /INITL/ F, PHI, SSAM, TME, TMPG, TMPS, VFR
C
C
C     H08  OR 008
      IF(HEIGHT)230,240,240
 230  D=2.181595
      Q=-ZSCL
      R=1.125E+02+(7.55E-01)*Q-(9.6E-06)*(Q**3.0)-(9.11E-12)*(Q**5.0)
      S=3.27E+01+(8.51E-01)*Q-(2.52E-05)*(Q**3.0)+(1.78E-10)*(Q**5.0)
      SSAM= D*((W)**(3.0/3.4))*(R**2.0)*S
      GO TO 250
 240  E=0.07740685
      SSAM=E*((W)**(3.0/3.4))*((180.0-ZSCL)**2.0)*(360.0+ZSCL)
 250  RETURN
      END
