      SUBROUTINE ADVEC(NET,NETSU,Z3H,TI4UP,USUM,VSUM,DXSUM,DYSUM,RSUM,
     1WFZ,TSUM,CAVS,ZCH,ALT,ATP,PRS,RHO,ETA,TMAX,
     2ICF,JCF,NCF,KBHF,N(A1F,LTIMF,NATF)
C
C     H. G. NORMENT, ATMOSPHERIC SCIENCE ASSOCIATES - DECEMBER 1978
C
C
C     FALLOUT PARCELS ARE TRANSPORTED (VIA SR TRANP) BY ADVECTION PLUS
C     SETTLING. PARCEL TCF AND BASE ARE TRANSPORTED SEPARATELY, AND THE
C     RESULTS ARE SMEARED. THE /COMMON/ VARIABLE ZP IS REDLFINEU.
C
C
      COMMON /CNTROL/ IPOUT,ISIN,ISOUT,JPARN,MC(20),NSEQO
      COMMON /PARCL/  CROSS,DOWN,DWAF,EDDY,NOATP,PMAS,FSIZ,RHOP,RWAF,
     1 TP,XP,YP,ZLOW,ZP
      COMMON /SPACE/ WIN1,XLLC,YLLC,ZMAX,ZMIN,TIMEX
C
      DIMENSION NET(ICF,JCF),NETSU(NCF),ZBH(KBHF),USUM(KBHF,NDATF,LTIMF)
      DIMENSION VSUM(KBHF,NDATF,LTIMF),DXSUM(KBHF,NDATF,LTIMF)
      DIMENSION DYSUM(KBHF,NDATF,LTIMF),TIMUF(LTIMF),ZCH(KBHF)
      DIMENSION CAVS(KBHF),WFZ(KBHF,NOATF,LTIMF),TSUM(KBHF)
      DIMENSION RSUM(KBHF,NOATF,LTIMF)
      DIMENSION ALT(NATF),ATP(NATF),PRS(NATF),RHC(NATF),ETA(NATF)
C
      DATA EPS/0.1/
C
      MC3=MC(3)
CHANGE ZP FROM PARCEL CENTER TO PARCEL BASE ALTITUDE.
      ZP=ZLOW
CALCULATE TRANSPORT OF PARCEL BASE.
      IF (   (ZP-ZMIN).GT.EPS) GO TO 1411
      TOL=TP
      XOL=XP
      YOL=YP
      ZOL=ZP
      ROL=0.
      SIGXL=RWAF
      SIGYL=RWAF
      GO TO 1412
 1411 CALL       TRANP(NET,NETSU,ZBH,TIMUP,USUM,VSUM,DXSUM,DYSUM,RSUM,
     1HFZ,CAVS,TSUN,TMAX,XCL,YOL,ZOL,TOL,SIGXL,SIGYL,RCL,NOATL,
     2ICF,JCF,NCF,KBHF,NDATF,LTIMF)
CHANGE ZP FROM PARCEL BASE TO PARCEL TOP ALTITUDE.
 1412 ZP=ZLOW+DWAF
CALCULATE TRANSPORT OF PARCEL TOP.
      IF( ZP-ZMIN .GT.EPS) GO TO 1414
      TOU=TP
      XOU=XP
      YOU=YP
      ZOU=ZP
      ROU=0.
      SIGXU=RWAF
      SIGYU=RWAF
      GO TO 1415
 1414 CALL       TRANP(NET,NETSU,ZBH,TIMUP,USUM,VSUM,CXSLM,DYSUM,RSUM,
     1WFZ,CAVS,TSUM,TMAX,XCU,YOU,ZOU,TOU,SIGXU,SIGYU,RCU,NDATU,
     2ICF,JCF,NCF,KBHF,NDATF,LTIMF)
CALCULATE SMEAR OF PARCEL TOP AND BASE RESULTS.
 1415 ZOUTN=(ZOL+ZOU)/2.
      TOUTN=(TOL+TOU)/2.
      IF(ABS(XOU-XOL).GE.1.0E-30) GO TO 1404
      IF(ABS(YOU-YOL).GE.1.0E-30) GO TO 1403
      ROUTN=0.
      GO TO 1405
 1403 ROUTN=1.57079633
      GO TO 1405
 1404 ROUTN=ATAN((YOU-YOL)/(XOU-XOL))
      IF(XOU-XOL .LT. 0.1) ROUTN=ROUTN - SIGN(3.141592E54,ROUTN)
 1405 R=ROUTN-ROL
      SXL=1./SQRT((COS(R)/SIGXL)**2+(SIN(R)/SIGYL)**2)
      SYL=1./SQRT((SIN(R)/SIGXL)**2+(COS(R)/SIGYL)**2)
      R=ROUTN-ROU
      SXU=1./SQRT((COS(R)/SIGXU)**2+(SIN(R)/SIGYU)**2)
      SYU=1./SQRT((SIN(R)/SIGXU)**2+(COS(R)/SIGYU)**2)
      SXOTN=(SXU+SXL+SQRT((XOU-XOL)**2+(YOU-YOL)**2))/2.
      SYOTN=SQRT(SYU*SYL)
      XOUTN=XOL+(SXOTN-SXL)*COS(ROUTN)
      YOUTN=YOL+(SXOTN-SXL)*SIN(ROUTN)
 1450 CALL DUMPER(XOUTN,YOUTN,ZOUTN,TOUTN,SXOTN,SYOTN,PMAS,PSIZ,ROUTN,J,
     1ISOUT,IPOUT,MC3)
      RETURN
      END
