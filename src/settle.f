      SUBROUTINE SETTLE(O,RHOP,RHO,ETA,T,P,V,I)
C
C     H. G. NORMENT, ATMOSPHERIC SCIENCE ASSOCIATES - DECEMBER 1978
C
C     COMPUTES STILL-AIR SETTLING SPEED OF RIGID SPHERES ACCORDING TO
C     THE EQUATIONS OF BEARD (JAS33,852(1976)) FOR SMALL SPHERES
C     (CORR .LE. 84.175), AND DAVIES(PROC.PHYS.SOC.(LONDON)57,256(1945))
C     FOR LARGER SPHERES.
C
C     GLOSSARY (SI UNITS)
C     C       4.0*G/3.0   WHERE G IS ACCELERATION OF GRAVITY (9.8)
C     CORR    DAVIES NUMBER
C     D       SPHERE DIAMETER
C     ETA     VISCOSITY
C     P       PRESSURE
C     RHO     FLUID DENSITY
C     RHOP    SPHERE DENSITY
C     T       TEMPERATURE
C     V       SETTLING SPEED
C     I       ACCURACY INDICATOR
C             I = 0 RESULT IS ACCURATE
C             I = 1 RESULT IS INAGGURATE, DAVIES NUMBER IS TOO LARGE
C
      DATA C/13.066667/
C
      I = 7
COMPUTE DAVIES NUMBER
      CDRR = C*(RHOP-RHO)*RHO*C**3/ETA**2
CHECK DAVIES NUMBER VALUE FOR ROUTING
      IF(CDRR.GT.  0.3261) IF(CDRR-84.175) 1(0,100.200
COMPUTE VIA STOKES-LAW EQUATION
      V = CDRR*ETA/(24.0*RHO*D)
      GO TO 530
COMPUTE VIA BEARDS EQUATION
 100  Y = ALOG(CORR)
      V = ETA/(RHO*D)*EXP(-3.18657 + Y*(0.992696 + Y*(-0.153193E-2
     1+Y*(-0.987059E-3 + Y*(-0.578878E-3 + Y*(0.855176E-4
     2-Y*0.327815E-5))))))
      GO TO 500
COMPUTE VIA DAVIES EQUATIONS
 200  IF(CORR.GT.140.)IF(CORR-4.5E7)400,400,300
      V = ETA/(RHO*D)*CORR*(4.16666667E-2 + CORR*(-2.3363E-4
     1+CDRR*(2.0154E-6-CDRR*6.9105E-9)))
      GO TO 500
 300  I = 1
 400  Y = ALOG10(CORR)
      V = ETA/(RHO*D)*(10.0)**(-1.29536 + Y*(0.986 + Y*(-0.046677+
     1Y*1.1235E-3)))
      RETURN
CORRECT SETTLING SPEED FCR SLIP
 500  V = V*(1.0 + 54.088*ETA*SQRT(T)/F/D)
      RETURN
      END
