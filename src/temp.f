      SUBROUTINE TEMP
C
C     H. G. NORMENT, ATMOSPHERIC SCIENCE ASSOCIATES - DECEMBER 1976
C .
C
C     ESTIMATES TEMPERATURES OF CONDENSED AND VAPOR PHASE FALLOUT IN
C     THE FIREBALL  AT THE INITIAL TIME.
C
C
      COMMON /BASIC/ W.FW,ZBRSTZ,HEIGHT,ZSCL,SLDTMP,TMSD,XGZ,YGZ,TGZ
      COMMON /INITL/ F, PHI, SSAM, TME, TMPG, TMPS, VFR
C
C
C     COMPUTE VAPOR TEMPERATURE
      Q=ZSCL*W**(-.03921)
      T2M=0.037*((0.045/0.037)**(Q/180.))*(W**(0.49-(0.07*Q/180.)))
      A=5980.*((1.145)**(Q/180.))*((W)**(-0.03948+0.02637*Q/180.0))
      B=-0.4473*(W**(0.04360))
      TMPG=A*((TME/T2M)**B)+1500.0
C
C     COMPUTE TEMPERATURE OF CONDENSED PHASE MATTER
      TMPS = 200. * ALOG10(W) + 1000.
      RETURN
      END
