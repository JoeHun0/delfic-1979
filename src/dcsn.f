      SUBROUTINE DERIV
C
C     H. G. NORMENT, ATMOSPHERIC SCIENCE ASSOCIATES - DECEMBER 1978
C
C
C     COMPUTES DIFFERENTIALS OF THE CLOUD PROPERTIES IN PREPARATION FOR
C     INTEGRATION OVER A TIME STEP
C
C
       COMMON /ATMOS/ NAT, ALT(256),  ATP(256),  PRS(256), RLH(256),
     1        RHO(256), ETA(256), NHODO, ZV(1J0),  VX(10C), VY(1J0)
      COMMON /CLOUD/ CHANGE,CMLR  ,C2    ,C3    ,C6    ,DEK    ,ORM    ,
     1 DS    ,DST   ,DST0  ,DST1  ,DST2  ,DT    ,DU    ,DWT    ,DX     ,
     2 DZ    ,ED    ,EK    ,EPS   ,ES    ,HLF   ,KS    ,KSV    ,MWYA   ,
     3 N     ,NNN   ,P     ,PH    ,R     ,RA    ,RL    ,RM     ,RZT    ,
     4 S     ,SAVE  ,SHAPE ,SMALLT,T     ,TE    ,U     ,V      ,WT     ,
     5 X     ,XE    ,Z     ,ZBFR  ,ZLMT  ,SPARE
      COMMON /INITL/ F, PHI, SSAM, THE, TMPG, TMPS, VPR
C
C
      DZ=U
C
C
C     OBTAIN VALUES OF AMBIENT TEMPERATURE, PRESSURE ,RELATIVE HUMIDITY
      CALL TRPL(Z,NAT ,ALT,ATP,TE)
      CALL TRPL(Z,NAT ,ALT,PRS,P)
      CALL TRPL(Z,NAT ,ALT,RLH,HLR)
C
C
C     COMPUTE AMBIENT AIR WATER MIXING RATIO
C
      XE=109.98*HLR*(TE/273.)**(-5.13)*EXP((25.*(TE-273.))/TE)/(P*29.)
      TAO=0.
C
C     COMPUTE SPECIFIC HEAT OF IN-CLOUC AIR
C
      IF(T-2300.)15,15,16
   15 TPR=T
      CP=946.6+0.1971*T
      GO TO 17
   16 TPR=2300.
      TAD=-3587.5*(T-TPR)+1.0625*(T**2-TPR**2)
      CP=-3567.5+2.125*T
   17 CP=(CP+X*(1697.66+1.144174*T))/(1.+X)
      CPAI=TAD+946.6*(TPR-TE)+(.09855*(TPR**2-TE**2)
C
C     COMPUTE SPECIFIC HEAT OF IN-CLOUC AIR-WATER-SOIL MIXTURE
C
      RMIX=(1.+X)/(1.+X+S+WT)
      CR=CP*RMIX
      IF(THPS-T)380,381,381
  381 IF(T-848.)3810,3810,3811
 3810 CS=781.6+0.5612*T-1.881E7/T**2
      GO TO 3812
 3811 CS=1003.8+0.13510*T
 3812 CR=CR+CS*(S+WT)/(1.+X+S+HT)
  380 QXE=(1.+XE)/(1.+29.*XE/18.)
      QX=(1.+29.*X/18.)/(1.+X)
      QT=T/TE
C
C     COMPUTE HORIZONTAL RADIUS OF CLOUD
C
      R=SQRT(3.*V/(RZT*12.5663706E0))
C
C     IS CLOUD CENTER ALTITUDE GREATER OR LESS THAN ALTITUDE OF PREVIOUS
C     TIME STEP
C        GREATER- TO 1101
C        LESS - TO 1100
      IF(KS,GT.0)GO TO 1102
      IF(Z-ZBFR)1100,1101,1101
 1100 DZ=0.
      U=0.
      DU=0.
      NNN=2
      GO TO 1102
 1101 NNN=1
C
C COMPUTE CLOUD S TC VOLUME RATIO
C
 1102 SV=12.5663706*R**2/V
C
C     COMPUTE TURBULENT KINETIC ENERGY DISSIPATION RATE
C
      EPS=C3*(2.*EK)**1.5/RZT
      Q7=AMAX1(ABS(U),SQRT(2.*EK))
      QQ=QT*QX*QXE*(1.+X+WT)/(1.+X+S+WT)
      IF(NHODO)1103,1103,1104
 1103 VS=0.0
      GO TO 1105
C
C     COMPUTE WIND SHEAR CIRRECTION FACTOR
C
 1104 ZTP=Z+RZT
      ZBT=Z-RZT
      CALL TRPL(ZTP,NH000,ZV,VX,VXT)
      CALL TRPL(ZTP,NH0DO,ZV,VY,VYT)
      CALL TRPL(ZBT,NH000,ZV,VX,VXB)
      CALL TRPL(ZBT,NHODO,ZV,VY,VYB)
      VS=SQRT((VXT-VXB)**2 + (VYT-VYB)**2)
 11C5 RS=SV*Q7+1.5*C6*VS/R
      GO TO (100,101,100),N
C
C     DRY EQUATIONS
C
C
C     COMPUTE AIR ENTRAINMENT RATE
C
  100 DRM=(RM/(1.-CPAI/(CP*T*QX)))*RMIX*(RS   *RL+(QT*QX*QXE*9.8*U-EPS)*
     1RMIX/(CR*T*QX)-9.8*U/(287./QXE*TE))
      ORME = DRM
C
C     SUBTRACT AWAY RATE CF MASS LOST CUE TO PARTICLES FALLING OUT CLOUD
C     BOTTOM DURING RISE
C
      DRM=DRM-CMLR
C
C     COMPUTE TIME DERIVATIVE OF WATER VAPOR MIXING RATIO
C
      DX=-(1.+X+S)/(1.+XE)*(X-XE)*DRME/RM
C
C     COMPUTE TIME DERIVATIVE OF CLOUD TEMPERATURE
C
      DT=-(RMIX*(QT*QX*QXE*9.8*U-EPS)+CPAI*DRME/RM)/CR
      WT=0.
C
C     NO CHANGE IN LIQUID WATER MIXING RATIO
C
      DWT=J.
      GO TO 555
C
C     WET EQUATIONS
C
  101 Q1=1.+X*29./18.
      IF(T-273.)102,103,103
  102 CL=2.83E6
      GO TO 104
  103 CL=2.5E6
  104 Q2=CL*X/(287.*T)
      03=18.*02/29./T
      Q4=1.+Q2
      Q5=1.+GL+Q3/CP
      Q6=CL*(X-XE)/CP+T-TE
      Q9=RMIX/Q5
      Q8=Q9/T/QX
C
C- 1999-01-01 17:01 01/01/01 01/01/01 01/01/01 01/01/01 01/01/01 01/01/0
C
      DRM=RMIX*(RM/(1.0-Q6*Q8))*(RS*RL+(QX*QT*9.8*Q4*U*QXE-EPS)/CP/T/QX*
     1Q9-(9.8*U)/(287./QXE*TE))
      DRME=DRM
C
C     SUBTRACT AWAY RATE OF MASS LOST DUE TO PARTICLES FALLING OUT CLOUD
C     BOTTOM DURING RISE
C
      DRM=DRM-CMLR
C
C     COMPUTE TIME DERIVATIVE OF TEMPERATURE
C
      DT=((-QX*QT*Q4*9.8*U/CP*QXE-Q6*DRME/(RMIX*RM))+EPS/CP)*Q9
C
C     COMPUTE TIME DERIVATIVE CF WATER VAPOR MIXING RATIO
C
      DX=Q1*(Q3*DT+9.8*X*U/(287.*TE)*QXE)
C
C     COMPUTE TIME DERIVATIVE OF LIQUID WATER MIXING RATIO
C
      DWT=-(1.+X+S+WT)/RM* (WT+X-XE)/(1.+XE)*DRME-DX
C
  555 E01= 2.*C2*Q7*QQ/RZT
      GO TO (621,1110),NNN
  621 CONTINUE
C
C     COMPUTE CLOUD VERTICAL ACCELERATION
C
      DU =  9.8 * (QT*QX*QXE*RMIX-1.) - ( ED1 + DRM/RM ) * U
C     COMPUTE EDDY VISCOUS RATE OF LOSS OF KINETIC ENERGY OF RISE
C
 1110 EO=E01*U**2
C     COMPUTE TIME DERIVATIVE OF TURBULENT KINETIC ENERGY DENSITY
C
      DEK=ED-(EK-0.5*U**2)*DRME/RM-EPS
C
C     COMPUTE TIME DERIVATIVE OF SOIL MIXING RATIO
C
      DS=-(1.+X+S+WT)*S/RM*(CMLR/(S+WT)+DRME/(1.+XE))
C
C     COMPUTE IN-CLOUD GAS DENSITY
C
      PA=RM/V*RMIX
      IF(EPS)902,902,901
  902 EPS=1.0E-4
  901 RETURN
      END
