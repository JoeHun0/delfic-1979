      SUBROUTINE DCSN
C
C     H. G. NORMENT, ATMOSPHERIC SCIENCE ASSOCIATES - DECEMBER 1978
C
C
C     DCSN DETERMINES AT THE END OF EACH TIME STEP WHETHER TO
C     CONTINUE THE CRM COMPUTATION
C
C
      COMMON /CLOUD/ CHANGE,CMLR  ,C2    ,C3    ,C6    ,DEK    ,ORM    ,
     1 DS    ,OST   ,OST0  ,OST1  ,OST2  ,DT    ,DU    ,DWT    ,OX     ,
     2 DZ    ,ED    ,EK    ,EPS   ,ES    ,HLR   ,KS    ,KSV    ,MWYA   ,
     3 N     ,NNN   ,P     ,PW    ,R     ,RA    ,RL    ,RM     ,RZT    ,
     4 S     ,SAVE  ,SHAPE ,SMALLT,T     ,TE    ,U     ,V      ,WT     ,
     5 X     ,XE    ,Z     ,ZBFR  ,ZLNT  ,SPARE
      COMMON /CONTRL/ DETID(12),IC(20),IRAD,IRISE,ISIN,ISOUT,JPARN,KDI
C
  06E FORMAT(14H0SWITCH TC DRY)
  C77  FORMAT(14H0SWITCH TO WET)
  088 FORMAT(1H1, 9X, 46HCLOUD RISE IS TERMINATED IN DCSN AT STATEMENT I
     14, 8H BY THE A6, 7H SWITCH///)
C
      DATA WORD1,      WORD3,WORD4 /6H TEMP ,         6H ZLMT ,6HR.LT.1/
C
C
      GO TO (151,154,1531),N
C
C      SHOULD WE SWITCH TC WET MODE---
C             YES-- TO 041
C
 1531 IF(ES-PW)041,041,008
C
  041  N=2
      IF(IC(5))151,151,1041
 1041 WRITE(ISOUT,77)
       GO TO 151
C
C 154 SHOULD WE SWITCH TO CRY MODE-
C       NO TO 151
C
  154 IF(WT + 1.0E-8)153,153,151
  153 N=1
      WT=0.
      DWT=0.
      IF(IC(5))151,151,152
  152 WRITE(ISOUT,66)
C
C     TEST FOR TIME STEP CHANGE
C
  151 IF (SMALLT - CHANGE) 014, 015, 015
  015  DST=DST2
C
C     TEST FOR ANOMALOUS CLOUD RISE AND SET UP TERMINATION CONDITION IF
C     ANOMALY IS FOUND
C
C
C
  014 IF(ABS(T)-10.)114,20,25
  114 NSTAT=14
      WORD=WORD1
      GO TO 1
C
C     TEST FOR R.LT.1 ANCMALY
C
  020  IF(R-1.) 125,13,13
  120 NSTAT=20
      WORD=WORD4
      GO TO 1
C
C     TEST FOR ZLMT ANOMALY
C
  013 IF (Z - ZLMF) 008, 008, 113
  113 NSTAT=13
      WORD=WORD3
C                                         COMPLETE CX TABLE
  001 MWYA = 3
      WRITE(ISOUT,88) NSTAT,WORD
  008 RETURN
      END
