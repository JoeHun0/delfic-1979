      SUBROUTINE ERROR (PROGRM,IRROR,ISOUT)
C     T. W. SCHHENKE
C     1 MARCH 1966
C
C
C     THIS PROGRAM WRITES A GENERALIZED ERROR COMMENT OF THE FOLLOWING
C     FORM ON TAPE ISOUT AND THEN RETURNS IF THE SIGN OF IRROR IS
C     POSITIVE OR STOPS IF ITS SIGN IS NEGATIVE.
C
C         ERROR SENSED IN PROGRAM (PROGRM) AT CR NEAR STATEMENT NUMBER
C         (IRROR).  PLEASE REFER TO THE PROGRAM LISTING.
C
C     PRIOR TO CALLING ERRCR  THE PARAMETER  PROGRM  MUST BE SET
C                                   WITH THE BCD NAME CF THE CALLING
C     PROGRAM AND PARAMETER  IRROR  MUST BE SET WITH THE NUMBER OF THE
C     FORTRAN STATEMENT WHICH BEST IDENTIFIES THE ERROR CONDITION.
C
C
 1    FORMAT(//26H ERROR SENSED IN PROGRAM  A6,3GH  AT OR NEAR STATEMENT
     1 NUMBER I6,40H .  PLEASE REFER TO THE PROGRAM LISTING.)
C
C
      IRR= IA8S(IRROR)
      WRITE(ISOUT,1)PROGRM,IRR
      IF(IRROR)101,100,100
  100 RETURN
  101 STOP
      END
