C
      IF (NN1-JTOPV)2072,2072,2073
C
C2072 NOW SELECT UEST NN POINTS
C     SCAN THE SET D2(J),J=NAD(NN+1,JTOPV) UNTIL A D2(J) LESS THAN DM
C     IS FOUND.  IF ONE IS FOUND, SWITCH NAD(NAOT) WITH THE SELECTED NAD
C THEN RESET DM AND NACT TO INDICATE THE MCST REMOTE OF THE NEAREST
C     NN POINTS.  WHEN THE FULL SET D2(J),J=NAC(NN+1,JTOPV) HAS BEEN
C     SCANNED, THE SET OF NEAREST DATA POINTS HAS BEEN SELECTED.  ONLY
C     ONE SCAN IS REQUIRED.
 2072 DO 210 J=NN1,JTOPV
      KL=NAD(J)
      IF(DM-D2(KL))210,210,211
 211  NTEMP=NAD(J)
      NAD(J)=NAD(NADT)
      NAD(NADT)=NTEMP
C
C     NOW RESET DM AND NADT TO THE NEW HOST REMOTE POINT
      DM=D2(KL)
      DO 212 KKK=1,NN
      KL=NAD(KKK)
      IF(DM-D2(KL))213,212,212
 213  DM=D2(KL)
      NADT=KKK
C
C     DM AND NAOT ARE SET WITH THE PARAMETERS OF THE MCST REMOTE OF
C     THE NEAREST NN POINTS
 212  CONTINUE
 210  CONTINUE
 2073 CONTINUE
C
C     THE NEAREST NN HAVE BEEN FOUND
C
C
C2080 COMPUTE AND SUM  THE WEIGHTING FACTORS
 2080 SUM=0.0
      DO 214 J=1,NN
      L=NAD(J)
      D2(L)=1.0/D2(L)
 214  SUM=SUM+D2(L)
      IF(SUM/FLOAT(NN) .LE. GIB) WRITE(ISOUT,24) NN,XG,YG,ZG
C
C     NOW COMPUTE VECTOR ESTIMATE AT LATTICE CENTER POINT.
C     COMPUTE STORAGE INDEX
C     COMPUTE AND STORE VECTOR ESTIMATE AT LATTICE CENTER POINT.
      VXKNL=0.0
