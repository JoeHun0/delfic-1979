C     ALSO SEE OPMI GLOSSARY
C
      COMMON /CONDAT/       IC(20)    ,IHOB      ,IPNCH     ,IPOUT     ,
     1ISIN      ,ISOUT     ,JPOUT     ,KPOUT     ,KTAPE     ,LTAPE     ,
     2MARRAY    ,MBTAPE    ,MXREQ     ,SD        ,INPAM
