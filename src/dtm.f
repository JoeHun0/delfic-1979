      IF(MC(2) .NE. 1  .AND.  SPEC .EQ. TURB) WRITE(ISOUT,33)J,AP(N1),
     1 AP(N5),AP(N6),AP(N2),AP(N3)
      IF(J.GT.JTOPF) CALL ERROR(PROGRM,-100,ISOUT)
      ZS(J) = (AP(N1) + SCALE(4))*SCALE(1)
      XS(J) = (AP(N5) + SCALE(7))*SCALE(6)
