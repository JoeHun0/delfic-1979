      SUBROUTINE SRTCNT( X, Y, CNT, K, CROLBL)
C
C     H. G. NORMENT, ATMOSPHERIC SCIENCE ASSOCIATES - MARCH 1979
C
C
C     GIVEN AN UNORDERED SET OF CONTOUR POINTS, THE POINTS ARE
C     SEQUENCED SUCH THAT EACH SUCCESSOR POINT IS THE CLCSEST POINT TO
C     ITS PREDECESSOR.  EACH CLOSED CONTOUR IS SEGREGATED.
C
C **************************** GLOSSARY ******************************:
C
C        x,y  -    POINT CCURDINATES
C        CNT  -    CONTOUR VALUE
C        K    -    NUMBER CF POINTS
C        XX,YY-    FIRST PCINT ON A CONTOUR
C        XP,YP-    MOST RECENTLY FOUND POINT ON A CONTCUR
C
C
      COMMON/CONDAT/IC(20),IHOB,IPNCH,IPOUT,ISIN,ISOUT,JPOUT,KPOUT,
     1KTAPE,LTAPE,MARRAY,MBTAPE,MXREQ,SD,INPAM

      DIMENSION X(300), Y(300)
      DATA CLR, PROGRM/ 1.E30, 6HSRTCNT/
      DATA CODE/ 6HDELFIC/
      VEC(A,B,C,D) = (A-C)**2 + (B-D)**2
      ILOOP=0
   40 IF( K .GT. 3) GO TO 55
      WRITE(ISOUT, 3000)
      DO 50 I=1,K
      WRITE( ISOUT, 1000) CNT,X(I), Y(I)
   50 IF(IPNCH .GT. 0) WRITE(IPNCH,2000)CNT, X(I),Y(I),CROLBL, CODE
      IF(IPNCH .GT. 0) WRITE(IPNCH,2000)CNT, X(1),Y(1),CROLBL, CODE
      WRITE(ISOUT, 1000)  CNT,X(1), Y(1)
      RETURN
CHECK POINTS AND REARRANGE IF NECESSARY TO AVOID A TWO-POINT CLOSURE
   55 ILOOP=ILOOP+1
      IF(ILOOP .GT. K) GO TO 100
      VEM=VEC(X(1),Y(1),X(2),Y(2))
      M=2
      DO 60 I=3,K
      IF(VEC(X(1),Y(1),X(I),Y(I)) .GT. VEM) GO TO 60
      M=I
      VEM=VEC(X(1),Y(1),X(I),Y(I))
   60 CONTINUE
      DO 65 I=2,K
      IF(I .EQ. M) GO TO 65
      IF(VEC(X(M),Y(M),X(I),Y(I)) .LE. VEM) GO TO 100
   65 CONTINUE
      XP=X(1)
      YP=Y(1)
      DO 70 I=2,K
      X(I-1)=X(I)
   70 Y(I-1)=Y(I)
      X(K)=XP
      Y(K)=YP
      GO TO 55
