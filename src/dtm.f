      SUBROUTINE CONTOR( CONTUR, CROLBL ,OMAP ,NMAP)
C
C     H. G. NORMENT, ATMOSPHERIC SCIENCE ASSOCIATES - JANUARY 1979
C
C
C     DETERMINE UNORDERED SETS OF POINTS ( A MAXIMUM CF 300 IS ALLOWED)
C     THAT LIE ON THE CONTOURS SPECIFIED BY ARRAY CONTUR.   LINEAR
C     INTERPOLATION BETWEEN MAP POINTS IS USED.   SK SRTCNT IS CALLED TO
C     ORDER THE POINTS IN SEQUENCE AROUND THE CLOSED SECTIONS OF THE
C     CONTOURS.
C
C
      COMMON/CONDAT/IC(20),IHOB,IPNCH,IPOUT,ISIN,ISOUT,JPOUT,KPOUT,
     1KTAPE,LTAPE,MARRAY,MBTAPE,MXREQ,SD,INPAM

      COMMON /MAPDAT/ CAYF ,CUTMAP    ,DGX       ,DGY       ,IH  ,IV   ,
     1JC        ,NXMAP     ,NYMAP     ,NZ        ,QCUT      ,SSAM      ,
     2TGZ       ,XGZ       ,X1        ,X2        ,YGZ       ,XMAX      ,
     3XMIN      ,YMAX      ,YMIN      ,ZMIN
      DIMENSION OMAP(NMAP),CONTUR( 8),X(300),Y(360)
      DATA PROGRM/6HCONTOR/
C
      DO 990 L=1,8
      IF( CONTUR(L) .EQ. 0.0) GO TO 999
      CNT = CONTUR(L)
      K = 0
COMPUTE CONTOUR INTERSECTIONS ALONG MAP ROWS
      DO 400 I=1,NYMAP
      DO 400 J=2,NXMAP
      IF(OMAP(NXMAP*(I-1)+J-1) .LE. CNT) IF(OMAP(NXMAP*(I-1)+J) - CNT)
     1  400,200,200
      IF(OMAP(NXMAP*(I-1)+J) .GT. CNT) GO TO 400
  200 K = K + 1
      IF( K .GT. 300) CALL ERROR(PROGRM, -200, ISOUT)
      Y(K) = YMIN + I*DGY
      X(K) = XMIN + (J-1)*DGX + (CNT - OMAP(NXMAP*(I-1)+J-1))*DGX/
     1 (OMAP(NXMAP*(I-1)+J) - OMAP(NXMAP*(I-1)+J-1))
  400 CONTINUE
COMPUTE CONTOUR INTERSECTIONS ALONG MAF COLUMNS
      DO 900 J=1,NXMAP
      DO 900 I=2,NYMAP
      IF(OMAP(NXMAP*(I-2)+J) .LE. CNT) IF(OMAP(NXMAP*(I-1)+J) - CNT)
     1  900,700,700
      IF(OMAP(NXMAP*(I-1)+J) .GT. CNT) GO TO 900
  700 K = K + 1
      IF( K .GT. 300) CALL ERROR(PROGRM, -700, ISOUT)
      X(K) = XMIN + J*DGX
      Y(K) = YMIN + (I-1)*DGY + (CNT - OMAP(NXMAP*(I-2)+J))*DGY/
     1  (OMAP(NXMAP*(I-1)+J) - OMAP(NXMAP*(I-2)+J))
  900 CONTINUE
      DO 950 I=1,K
  950 WRITE(ISOUT,1100) X(I),Y(I), CNT
 1100 FORMAT( 3F10.0)
      CALL SRTCNT( X, Y, CNT, K, CRDL9L)
  990 CONTINUE
  999 RETURN
      END
