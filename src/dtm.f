      SUBROUTINE GETUP(NET,NETSU,MARY,MARF,ICF,JCF,NCF,NDATF)
C
C     MARCH, 1971
C
C
C     SUBROUTINE  GETUP  PREPARES THE HORIZONTAL SPACE CONTROL NET
C     ARRAYS  NET( IC, IC )  AND  NETSU ( NC ) FROM DATA PROVIDED BY THE
C     USER IN THE GRID SPECIFICATION ARRAY MARY( MARK ).
C
C THE SUBSCRIPTS IC AND JC OF THE TWO-CIMENSICAL ARRAY
C     NET( IC, JC )  LOCATE ( SYMBOLICALLY ) THE CENTERS OF CONTIGLOUS
C     UNIT MESH SQUARES ( CF DIMENSION  WINT ) RELATIVE TO THE UNIT
C      SQUARE IN THE SOUTH-WEST CORNER OF THE NET.      FOR THIS SOUTH-W
C     CORNER UNIT  MESH   IC = JC = 1.  IC  IS INCREMENTED IN THE
C     EASTERLY DIRECTION AND  JC  IS INCREMENTED IN THE NORTHERLY
C     DIRECTION.
C
C     ON FIRST PASS THROUGH THE ELEMENTS OF  MARY( MARK )  EACH POSITIVE
C     INTEGER FLAGS A PARTICULAR NON-SUBDIVIDED UNIT MESH SQUARE.  A 0
C     FLAGS A PARTICULAR SUBDIVIDED UNIT MECH SQUARE.
C     A UNIQUE VALUE OF NDATA ( THE ARRAY INDEX WHICH REFERENCES ALL OF
C     THE ATMOSPHERIC DATA ARRAY ELEMENTS ASSOCIATED WITH THIS UNIT
C     SQUARE ) IS STORED IN  NET( IC, JC ).
C
C     WHEN ZERO IS FOUND IN AN ELEMENT OF  MARY( MARK ) ,
C     NC  ( THE ARRAY INDEX WHICH REFERENCES A STARTING LOCATION IN THE
C     ARRAY  NETSU ( NC )  ) IS STORED IN  NET( IC, JC )  AS A NEGATIVE
C     INTEGER  -NC.
C
C     MARY( MARK )  IS ERASED AND RELOADED.  ON SECOND PASS THROUGH
C     THE ELEMENTS OF  MARY( MARK ), THE  ELEMENT  NC   OF THE ARRAY
C     NETSU ( NO )  WILL BE LOADED WITH CONTROL DATA PERTAINING TO THE
C     LOWER-LEFT QUADRANT OF THE SUBDIVIDED MESH SQUARE.  THE SUCCEEDING
C     THREE ELEMENTS ( NETSU ( NC+1 ), NETSU ( NC+2 ), NETSU ( NC+3 ) )
C     WILL BE LOADED WITH CONTROL DATA PERTAINING TO THE OTHER THREE
C     QUADRANTS, PROCEEDING CLOCKWISE FROM THE FIRST QUADRANT.  THESE
C     CONTROL DATA WILL BE ADDITIONAL  NOATA  OR  NC  VALUES FLAGGED BY
C     MARY( MARK ).
C
C     PROCESSING CONTINUES UNTIL NO ADDITIONAL ELEMENTS  NC  ARE FLAGGED
C     BY  MARY( MARK ).
C
      COMMON /CNTROL/ IPOUT,ISIN,ISOUT,JPARN,MC(20),NSEQO
      COMMON /INDEX/ ICX,JCX,KBHX,LTIMX,NAT,NCX,NDATX
      DIMENSION       NET(ICF,JCF),     NETSU(   NCF),      MARY(  MARF)
      DATA PROGRM/6HGETUP /
C
 1000 FORMAT( 36I2 )
 1001 FORMAT( 1H0, 25X, 31HARRAY MARY HAS BEEN LOADED WITH,I5, 22H ELEME
     1NT(S) AS FOLLOWS/)
 1002 FORMAT(25X,36I2)
C
      MSECT = 4
      MNEG = 1 - MSECT
      NDATA = 0
      IC = 0
      JC = 1
      IF(ICX.GT.ICF) CALL ERROR(PROGRM,-1,ISOUT)
      IF(JCX.GT.JCF) CALL ERROR(PROGRM,-1,ISOUT)
       MARX = ICX * JCX
    1 DO 2 MARK = 1, MARF
   2   MARY( MARK ) = -9
       IF(MARX.GT.MARF) CALL ERROR(PROGRM,-2,ISOUT)
       READ(ISIN,1000) (MARY(MARK),MARK=1,MARX)
       WRITE(ISOUT,1001) MARX
       WRITE(ISOUT,1002) (MARY(MARK),MARK=1,MARX)
       MARK = 0
       MCTR = 0
  3    MARK = MARK + 1
       IF( MARK - MARX ) 5, 5, 4
  4    MARX = MSECT * MCTR
       IF( MARX )  6, 14, 1
  5    IF( MARY( MARK ) )  6, 7, 8
  6    CALL ERROR(PROGRM,-6,ISOUT)
  7    MNEG = MNEG + MSECT
       NQQ = - MNEG
       MCTR = MCTR + 1
       GO TO 9
  8    NDATA = NDATA + 1
       NQQ = NDATA
       NDATX = NDATA
      IF(NDATX.GT.NDATF) CALL ERROR(PROGRM,-8,ISOUT)
  9    IC = IC + 1
       IF( JC - JCX ) 10, 10, 13
  10   IF( IC - ICX ) 12, 12, 11
  11   JC = JC + 1
       IC = 0
       GO TO 9
   12 NET( IC, JC ) = NQQ
       GO TO 3
  13   NC = IC
       NETSU( NC) = NQ Q
       NCX = NC
      IF(NCX.GT.NCF) CALL ERROR(PROGRM,-13,ISOUT)
       GO TO 3
  14   RETURN
      END
