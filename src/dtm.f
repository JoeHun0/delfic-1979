    5 VINT=VINT/2.
      IQ=(XQ-XL)/VINT
      JQ=(YQ-YL)/VINT
CONVERT NQ TO QUADRANT LABEL
      NQ=NQ+3*IQ+JQ-2*IQ*JQ
COMPUTE XL,XR,YL, AND YU FCR QUADRANT
      XR=XL+VINT*FLOAT(IQ+1)
      XL=XL+VINT*FLOAT(IQ)
      YU=YL+VINT*FLOAT(JQ+1)
      YL=YL+VINT*FLOAT(JQ)
CHECK SIGN OF NETSU(NQ)
      IF(NETSU(NQ)) 7,6,8
    6 CALL ERROR(PROGRM,-6,ISOUT)
CONTINUE QUADRANT SEARCH. CBTAIN POINTER NQ
    7 NQ=-NETSU(NQ)
      GO TO 5
CONCLU DE QUADRANT SEARCH
    8 NDATA=NETSU(NQ)
      RETURN
      END
