      SUBROUTINE PDMP
C
C     THIS SUBROUTINE SOPTS OUT THOSE  PARCELS  THAT WILL CONTRIBUTE
C     TO SUBSEQUENT MAP CORE LOAJS, AND DUMPS THEM ON TO TAPE FOR
C TEMPORARY STORAGE
C
C     H.G.NORMENT     JUNE 28,1971
C  GLOSSARY
C     JL           COUNT CF  PARCELS  MOVED FROM UPPER TO LOWER CORE
C                  (JL.LE.KP)
