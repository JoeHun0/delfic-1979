      IF( VEC( XP, YP, X(I), Y(I))  .GT. VEM) GO TO 700
      M = I
      VEM = VEC( XP, YP, X(I), Y(I))
  700 CONTINUE
  701 XP = X(M)
      YP = Y(M)
      X(M) = CLR
      WRITE( ISOUT, 1000) CNT, XP, YP
      IF(IPNCH .GT. 0) WRITE(IPNCH,2000)CNT, XP,  YP,  CROLBL, CODE
  702 IF( VEC( XP, YP, XX, YY ) .EQ. 0.0) GO TO 750
      L= 1
      KK = KK + 1
  705 DO 710 I=1,K
      IF( X(I) .EQ. CLR) GO TO 710
      VEM= VEC( XP, YP, X(I), Y(I))
      M = I
      GO TO 600
  710 CONTINUE
      CALL ERROR( PROGRM, -710, ISOUT)
  750 IF( KK .EQ. K) RETURN
COMMENCE INITIALIZATION FOR ANOTHER CLOSURE.
CONDENSE REMAINING POINTS INTO LOWER CORE.
      KP=K-KK
      KKP=KP+1
      DO 770 I=1,KP
      IF(X(I) .NE. CLR) GO TO 770
      DO 760 J=KKP,K
      IF(X(J) .EQ. CLR) GO TO 768
      X(I)=X(J)
      Y(I)=Y(J)
      X(J)=CLR
      GO TO 768
  760 CONTINUE
  765 CALL ERROR(PROGRM,-765,ISOUT)
  768 KKP=J+1
  770 CONTINUE
      ILOOP=0
      K=KP
      GO TO 40
 1000 FORMAT( 5X, 3F10.0)
 2000 FORMAT( 3F10.0, 10X, A10, 10X, A6)
 3000 FORMAT(1H0)
      END
