C     NN -NEAREST- POINTS (THE POINTS WHOSE ADDRESSES ARE GIVEN BY
C     NAD(1),NAD(NN).) STORE THAT MAXIMUM DISTANCE IN THE WORD DM AND
C     SET NADT SUCH THAT DP=02(NAD(NADT)).
      KL=NAD(NADT)
      DM=D2(KL)
      DO 207 J=1,NN
      KL=NAD(J)
      IF(DM-D2(KL))208,207,207
 208  DM=D2(KL)
      NADT=J
 207  CONTINUE
