C                  (JP.LE.NE.AND.JP.LE.KP)
C     KP           NUMBER OF  FARCELS  IN CORE THAT ARE TO BE DUMPED
C                  ONTO TAPE
C                  (KP=NIJ-NE)
C     NE           COUNT OF AVAILABLE  PARCEL  STORAGE LOCATIONS IN
CORE. THIS IS THE NUMBER OF PARCELS REJECTED
C                  IN PCHECK.
