      VYKNL=VYKNL+SY(L)*D2(L)
 216  VZKNL=VZKNL+SZ(L)*D2(L)
      VXKNL=VXKNL/SUM
      VYKNL=VYKNL/SUM
      VZKNL=VZKNL/SUM
 2090 VX(KBH,NDATA,LTIM) = VXKNL
      VY(KBH,NDATA,LTIM) = VYKNL
      IF(FORM .EQ. TURB) GO TO 905
      VZ(KBH,NDATA,LTIM) = VZKNL
 905  CONTINUE
 906  CONTINUE
      RETURN
      END
CDECK,WILKNS
      SUBROUTINE WILKNS (ZCH,DXSUM,DYSUM,CAVS,TIMUP,KBHF,NDATF,LTIMF,L)
C     H. G. NORMENT, ATMOSPHERIC SCIENCE ASSOCIATES - DECEMBER 1978
C
C
C  WILKINS FUNCTION (JAS 20, 473(1963)) IN THE FCRM BELOW IS USED TO
C  COMPUTE TURBULENT KINETIC ENERGY DENSITY DISSIPATION RATE, EPS,
C
C     EPS=USTAR**3 / (0.25*(Z+Z0))
C
C  WHERE -
C     USTAR IS SURFACE LAYER FRICTION VELOCITY
C     Z0    IS SURFACE RCUGHNESS LENGTH
C     Z     IS ALTITUDE ABOVE GZ.
C
C USTAR IS COMPUTED FROM SURFACE WIND SPEED (U), HEIGHT AT WHICH U IS
C  MEASURED (ZM, USUALLY ZM=10 METERS), ROUGHNESS LENGTH (Z0), AND
C  RECIPROCAL MONIN-OBUKHOV LENGTH (RL), VIA THE EQUATION
C
C     USTAR=0.35*U / (ALCG(ZM/Z0)+CHI)
C
C  WHERE CHI IS CALCULATED BY EXPRESSIONS GIVEN BY BARKER AND BAXTER,
C  JAS 14, 620(1975).
C
C  IF U, ZM, ZO, AND RL ARE NOT INPUT, THE EQUATION
C
C     EPS=0.03/Z     (M**2/SEC**3)
C
C  IS USED.
C
C
      COMMON/CNTROL/IPOUT,ISIN,ISOUT,JPARN,MC(20),NSEQO
      COMMON/INDEX/ICX,JCX,KBHX,LTIMX,NAT,NCX,NDATX
      COMMON /SPACE/ WINT,XLLC,YLLC,ZMAX,ZMIN,TIMEX
      DIMENSION DXSUM(KBHF,NDATF,LTIMF),DYSUM(KBHF,NDATF,LTIMF)
      DIMENSION CAVS(KBHF),ZCH(KBHF),TIMUP(LTIMF)
C
      DATA PROGRM , VKK   , WILK   , ALIMIT
     1  /6HWILKNS , 0.35  , 0.03   , 999999./
C
 1000 FORMAT(4F10.0)
 5000 FORMAT(      19X, 1HK, 8X, 3HZCH, 12X, 5HDXSUM,10X, 5HDYSUM)
 5100 FORMAT( 15X, I5, 3(3X,E12.5))
 5200 FORMAT(    15X76HTURBULENCE PARAMETERS ARE CALCULATED BY WILKINS R
     1ECIPROCAL ALTITUDE FUNCTION/ 15X 10HFOR UPDATEI3,  4H AT E12.5,
     2 8H SECONDS/)
 5300 FORMAT( 14X, 22HSURFACE WIND SPEED IS E12.5, 3X, 20H MEASURED AT H
     1EIGHT E12.5/ 14X, 17HROUGHNESS LENGTH=E12.5, 3X, 32HRECIPROCAL MON
     2IN-0BUKHOV LENGTH=E12.5, 3X, 11H(MKS UNITS)/
     3 14X, 32HSURFACE LAYER FRICTION VELOCITY=E12.5, 3X,  7H(M/SEC)/)
 5900 FORMAT( 1H0,9X87HCANNOT COMPUTE TURBULENCE VIA WILKINS METHOD BECA
     1USE ZCH ARRAY HAS NOT BEEN CONSTRUCTED/ 10X, 53HCALCULATION CANNOT
     2 PROCEED UNLESS WIND DATA ARE INPUT//)
C
CHECK IF ARRAY ZCH HAS BEEN CREATED
      IF(ZCH(1) .NE. ALIMIT) IF(MC(2)-1)50,60,50
      WRITE(ISOUT,5900)
   25 CALL ERROR(PROGRM,-25,ISOUT)
   50 WRITE(ISOUT,5200)L,TIMUP(L)
C
C  READ  DATA USED TO CALCULATE USTAR (MKS UNITS)
C
   60 READ(ISIN,1000) U, ZM, Z0, RL
      IF(Z0 .EQ. 0.0) GO TO 300
      IF(RL .GE. 0.0) GO TO 100
C
C  COMPUTE CHI FOR AN UNSTABLE BOUNDARY LAYER
C
      XI = (1.0 - 15.0*ZM*RL)**0.25
      CHI = -ALOG((XI**2+1.0) * (XI+1.0)**2 /8.0) + 2.0*ATAN (XI)
     1 - 1.570796327
      GO TO 200
  100 CONTINUE
C
C  COMPUTE CHI FOR A NEUTRAL OR STABLE BOUNDARY LAYER
C
      CHI = 4.7*ZM*RL
  200 CONTINUE
      USTAR = VKK*U / (ALOG(ZM/Z0) + CHI)
      C = USTAR**3/VKK
      IF(MC(2) .NE. 1) WRITE(ISOUT,5300)U,ZM,Z0,RL,USTAR
      GO TO 400
  300 C = WILK
  400 CONTINUE
C
C  COMPUTE EPS AND STORE TEMPORARILY IN CAVS
C
      ZGZ = ZMIN
      DO 500 K=1,KBHX
  500 CAVS(K) = C/(ZCH(K) - ZGZ + Z0)
C
C  LOAD DIFFUSION PARAMETER ARRAYS
C
      DO 600 N=1,NDATX
      DO 600 K=1,KBHX
      DXSUM(K,N,L) = CAVS(K)
  600 DYSUM(K,N,L) = CAVS(K)
      IF(MC(2) .EQ. 1) RETURN
      WRITE( ISOUT, 5000)
      DO 700 K=1,KBHX
  700 WRITE(ISOUT,5100) K, ZCH(K), DXSUM(K,1,L),DYSUM(K,1,L)
      RETURN
      END
CDECK,CALC
      SUBROUTINE CALC(IP,OMAP,NMAP)
C
C     H.G.NORMENT     JUNE 25,1971
C
C
C     THIS SUBROUTINE COMPLTES MAP CONTRIBUTIONS FOR INDIVIDUAL
C     FALLOUT PARCELS
C
C ******************** GLOSSARY ********************
C
C     NOB          SMALLEST POSSIBLE Y INDEX OF A CONTRIBUTION ELLIPSE
C     NOL          SMALLEST POSSIBLE X INDEX OF A CONTRIBUTION ELLIPSE
C     NOR          LARGEST  POSSIBLE X INDEX OF A CONTRIBUTION ELLIPSE
C     NOT          LARGEST  POSSIBLE Y INDEX OF A CONTRIBUTION ELLIPSE
C     YREL         Y COORDINATE OF THE MAP POINT ROW CURRENTLY BEING
C                  ONSIDEREDR ELATIVET OT HEP  ARCELB   Y COORDINATE
C     XREL         X COORDINATE OF THE MAP POINT     CURRENTLY BEING
C CONSIDERED RELATIVE TO THE PARCEL X COURINATE
C     XL           LEFT BCLNDRY X COORDINATE  CF THE PARCEL
C                  CONTRIBUTION ELLIPSE IN THE YREL MAF ROW
C     XR           RIGHTBOLNERY X COORDINATE  OF THE PARCEL
C                  CONTRIBUTION ELLIPSE IN THE YKEL MAP POW
C     NHX          NUMBER CF MAP POINTS SPANNED BY A FARCEL
C                  CONCENTRATION ELLIPSE IN A ROW
C     VARX2        2.0*GAUSSIAN DISTBN. VARIANCE ALONG A AXIS
C     VARY2        2.0*GAUSSIAN DISTBN. VARIANCE ALONG B AXIS
C     F            MAGNITUDE(I.E. INTEGRATED VALUE) OF A FARGEL
C                  PROPERTY  TO BE DISTRIBUTED ON THE MAP
C
C     ALSO SEE OPM1  GLOSSARY  AND PCHECK GLOSSARY
C
C
      COMMON/CONDAT/IC(20),IHOB,IPNCH,IPOUT,ISIN,ISOUT,JPOUT,KPOUT,
     1KTAPE,LTAPE,MARRAY,MBTAPE,MXREQ,SD,INPAM

      COMMON/MAPDAT/CAYF,CUTMAP,DGX,DGY,IH,IV,JC,NXMAP,NYMAP,NZ,QCUT,
     1SSAM,TGZ,XGZ,X1,X2,YGZ,XMAX,XMIN,YMAX,YMIN,ZMIN


      COMMON /PARDAT/       ASQ       ,BSQ       ,COSA      ,F         ,
     1GAMA      ,KTR(100)  ,PMAS(100) ,PSIZ(100) ,RO(100)   ,SIGXO(100),
     2SIGYO(100),SINA      ,TPAR(100) ,XPAR(100) ,YPAR(100) ,YPRML     ,
     3YPRMU     ,ZPAR(100)
      COMMON /RUNDAT/      C          ,CF6       ,FSUM      ,ICTR      ,
     1MAPRUN    ,NE        ,NIJ       ,NORD      ,NREQ      ,NTASK     ,
     2OPMID(12) ,T1        ,T2        ,WFMAS(200)
      DIMENSION OMAP(NMAP)
      DATA PROGRM/6HCALC  /
C
C     INITIALIZE FOR THIS PARCEL
C
      VARX2= ASQ/GAMA
      VARY2= BSQ/GAMA
      A = SINA*COSA*(1.0/VARY2- 1.0/VARX2)*2.0
      B = 4.0/VARX2/VARY2
      CC= (COSA**2/VARX2 + SINA**2/VARY2)*2.0
      D = 2.0*GAMA*CC
      Q = F/SIGXO(IP)/SIGYO(IP)/6.28318531
C
C     COMPUTE SMALLEST Y INDEX OF A CONTRIBUTION
C
      NOB = (YPRML - YMIN)/DGY
      NOB=NOB+1
      IF(NOB.LT.1) NOB=1
  100 IF(NOB.LE.NYMAP) GO TO 120
  116 IRROR=-110
      GO TO 400
C
C     COMPUTE LARGEST  Y INDEX OF A CONTRIBUTION
C
  120 NOT = (YPRMU - YMIN)/DGY
      IF(NOT.GT.NYMAP) NOT=NYMAP
      IF(NOT.GT.0 ) GO TO 140
  130 IRROR=-130
      GO TO 400
C
C     ENTER THE MAP ROW LCCP
C
  140 DO 350 J=NOB,NOT
C
C     COMPUTE  THE LIMITING Y COORDINATES OF THE PARCEL CONTRIBUTION
C     ELLIPSE IN THIS ROW
C
      YREL = J
      YREL = YMIN + DGY*YREL - YPAR(IP)
      RADIC = -B*YREL**2+D
      IF(RADIC.GE.0.0) GO TO 160
  150 RADIC=0.0
      CALL ERROR(PROGRM,  150,ISOUT)
  160 RADIC=SQRT(RADIC)
      XL=XPAR(IP)+ (YREL*A- RADIC)/CC
      XR = XL + 2.0*RADIC/CC
C
C     COMPUTE SMALLEST X INDEX OF A CONTRIBUTION
C
      NOL = (XL-X1)/DGX
      NOL=NOL+1
      IF(NOL.LT.1) NOL=1
      IF(NOL.GT.NXMAP) GO TO 350
C
C     COMPUTE LARGEST  X INDEX OF A CCNTRIBUTION
C
  180 NOR = (XR-X1)/DGX
      IF(NOR.GT.NXMAP) NOR=NXMAP
      IF(NOR.LT.1) GO TO 350
  200 NWX = NOR - NOL
      IF(NWX+1)210,350,220
  210 IRROR=-210
      GO TO 400
C
C     COMPUTE OMAP(M) ARRAY INDEX EXTREMES FOR MAP POINTS IN THIS ROW
C
  220 MCRMT=(J-1)*NXMAP
      K = NOL + MCRMT
      L = K + NWX
C
C     ADJUST OR ADD CONTRIBUTIONS TO THE MAP POINTS
C
      GO TO (224,224,221,221,222,222),NORD
  221 OMA=TPAR(IP)
      GO TO 224
  222 OMA=PSIZ(IP)*1.0E6
  224 DO 300 M=K,L
      GO TO (225,245,230,240,230,240),NORD
  225 OMAP(M)=OMAP(M)+1.
      GO TO 300
  230 OMAP(M) = AMIN1(OMA,OMAP(M))
      GO TO 300
  240 OMAP(M) = AMAX1(OMA,OMAP(M))
      GO TO 300
  245 XREL=M   -MCRMT
      XREL = X1   + DGX*XREL - XPAR(IP)
      OMA = Q*EXP( - (XREL*COSA + YREL*SINA)**2/VARX2 - (YREL*COSA
     1 - XREL*SINA)**2/VARY2)
  250 OMAP(M) = OMAP(M) + OMA
  300 CONTINUE
  350 CONTINUE
      RETURN
  400 CALL ERROR(PROGRM,IRROR,ISOUT)
      END
