      IF (IFIX(DWAF).GT.0) GO TO 1200
      IF( MC  3.GT.0 )WRITE(ISOUT,8019                                )
      CALL       DUMPER(XP,YP,ZP,TP, RWAF, RWAF, PMAS,PSIZ,0.,0,
     1ISOUT,IPOUT,MC3)
      GO TO 1000
COMPUTE INDEX OF MESH OR SUB-MESH CONTAINING PARCEL CENTER.
 1200 CALL NEST(NET,NETSU,XP,YP,NDATP,XL,XR,YL,YU,ICF,JCF,NCF)
CANCEL PROCESSING OF PARCEL IF IT IS INPUT OUTSIDE ATMOS.
      IF(NDATP.GT.0) GO TO 1260
      IF( MC3 .GT. 0) WRITE(ISOUT,8020)
      GO TO 1000
CANCEL PROCESSING OF PARCEL IF IT CANNOT REACH THE GROUND IN THE ALLOTED
C     TIME
 1260 IF(ZLOW.LT.ZLIM) GO TO 1409
      IF( MC3 .GT. 0) WRITE(ISOUT,8015)
      GO TO 1000
 1409 CALL       ADVEC(NET,NETSU,ZBH,TIMUP,USUM,VSUM,DXSUM,DYSUM,RSUM,
     1WFZ,TSUM,CAVS,ZCH,ALT,ATP,PRS,RHO,ETA,TMAX,
     2ICF,JCF,NCF,KBHF,NDATF,LTIMF,NATF)
 1000 CONTINUE
      GO TO 100
COPY OUT BUFFER DATA VECTORS FOR DRY DEPOSIT INCREMENTS.  WAFER
C PROCESSING HAS BEEN COMPLETED
  806 CALL       DUMPER(0.,0.,0.,0.,   0.,   0.,   0.,  0.,0.,999,
     1ISOUT,IPOUT,MC3)
      CALL       DUMPER(0.,0.,0.,0.,   0.,   0.,   0.,  0.,0.,999,
     1ISOUT,IPOUT,MC3)
      REWIND JPARN
      ENDFILE IPOUT
      REWIND IPOUT
      RETURN
      END
