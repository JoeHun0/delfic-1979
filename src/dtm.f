      KBHM1=KBHX-1
      WAVGK=0.0
      DO 51 L=1,LTIMX
      DO 50 K=1,KBHM1
   50 WAVGK=WAVGK + WAVG(K,L)*(ZBH(K+1) - ZBH(K))
   51 WAVGK = WAVGK + WAVG(KBHX,L)*(ZMAX - ZBH(KBHX))
