      SUBROUTINE BOUN(NET,NETSU,XT,YT,XO,YO,XC,YC,ICF,JCF,NCF)
C     MARCH, 1971
C     SUBROUTINE BOUN DETERMINES AN INTERPOLATED PARCEL POSITION
C     (INFINITESMALLY DISPLACED EXTERNAL TO A CELL B(UNDARY) GIVEN THE
C     PREVIOUS PARCEL POSITION INTERNAL TO THIS CELL AND THE ANTICIPATED
C     PARCEL POSITION EXTERNAL TO THIS CELL
C     XT    - ANTICIPATED FARCEL POSITION X COORDINATE
C     YT    - ANTICIPATED PARCEL POSITION Y COORDINATE
C     XO    - PREVIOUS PARCEL POSITION X COORDINATE
C     YO    - PREVIOUS PARCEL POSITION Y COORDINATE
C     XC    - INTERPOLATED PARCEL POSITION X CCCRDINATE
C     YC    - INTERPOLATED PARCEL POSITION Y COORDINATE
C     ADISP - SMALL X DISPLACEMENT. + CR - EPS.
C     BDISP - SMALL Y DISPLACEMENT. + OR - EPS.
      DIMENSION NET(ICF,JCF),NETSU(NCF)
      DATA EPS/0.5/
CLEAR ADISP AND BDISP
      ADISP=0.
      BDISP=0.
COMPUTE XL,XR,YL, AND YU FCR (XO,YO)
      CALL NEST(NET,NETSU,XO,YO,NDATO,XL,XR,YL,YU, ICF,JCF,NCF)
CUT AND TRY XC
CHECK IF XT LIES TO THE RIGHT OF XR
      IF(XT.LE.XR) GO TO 102
      XC=XR
      ADISP=EPS
      GO TO 104
CHECK IF XT LIES TO THE LEFT OF XL
  102 XC=XL
      IF(XT.GE.XL) GO TO 106
      ADISP=-EPS
CCMPUTE YC
  104 YC=YO+(YT-YO)*(XC-XO)/(XT-XO)
CHECK IF YC LIES BETWEEN YL AND YU
      IF((YU.GE.YC).AND.(YC.GE.YL)) GO TO 111
CUT AND TRY YC
CHECK IF YT IIES ABOVE YU
 106  IF(YT.LT.YU) GO TO 108
      YC=YU
  107 BDISP=EPS
      GO TO 110
CHECK IF YT LIES BELOW YL
  108 YC=YL
      IF(YT.GT.YL) GO TO 111
      BDISP=-EPS
COMPUTE XC
  110 XC=XO+(XT-XO)*(YC-YO)/(YT-YO)
CREATE INFINITESMAL DISPLACEMENT
  111 XC=XC+ADISP
      YC=YC+BDISP
      RETURN
      END
