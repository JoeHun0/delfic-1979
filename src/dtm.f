      SUBROUTINE SPRVS(NET,NETSU,ZBH,ZCH,TIMUP,USUM,VSUM,DXSUM,DYSUM,
     1RSUM,WFZ,CAVS,HDAV,TSUM,WAVG,ALT,ATP,PRS,RLH,RHO,ETA,
     2ICF,JCF,NCF,KBHF,NDATF,LTIMF,NATF)
C
C     H. G. NORMENT, ATMOSPHERIC SCIENCE ASSOCIATES - DECEMBER 1978
C
C
C     SUBROUTINE SPRVS SUPERVISES DIFFUSIVE.TRANSPORT
C     OF FALLOUT PARCELS LISTED ON TAPE JPARN.  PARCEL PARAMETERS ARE
C     STORED IN ARRAYS XPAR,YPAR,ZPAR,TPAR,PDAM,PSAM,KWFR,DWFR,ZLWF,VHFR
C     ONLY ONE PARCEL IS TRANSPORTED AT A TIME. FOR THIS PARCEL ABOVE
C     ITEMS ARE STORED IN XP,YP,ZP,TP,PSIZ,PMAS,RWAF,DWAF,ZLOW,VWAF.
C     XPAR  - X COORDINATE OF FARCEL CENTER
C     YPAR  - Y COORDINATE OF PARCEL CENTER
C     ZPAR  - Z COORDINATE OF FARCEL CENTER
C     TPAR  - TIME OF DEFINITION OF CLOUD PARCEL
C     PDAM  - MIDPOINT OF PARCEL PARTICLE SIZE CLASS
C     PSAM  - TOTAL MASS OF PARCEL
C     RWFR  - RADIUS OF PARCEL AT CENTER OF MASS
C     DHFR  - PARCEL THICKNESS
C     ZLWF  - ALTITUDE OF FARCEL BASE
C     VHFR  - PARCEL VOLUME
C
C
      COMMON /CNTROL/ IPOUT,ISIN,ISOUT,JPARN,MC(20),NSEQO
       COMMON /INDEX/ ICX,JCX,KBHX,LTIMX,NAT,NCX,NDATX
      COMMON /PARCL/  CROSS,DOWN,DWAF,EDDY,NDATP,PMAS,PSIZ,RHOP,RWAF,
     1 TP,XP,YP,ZLOW,ZP
      COMMON /SPACE/ WINT,XLLC,YLLC,ZMAX,ZMIN,TIMEX
