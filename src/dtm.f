      SUBROUTINE NEST(NET,NETSU,XQ,YQ,NDATA,XL,XR,YL,YU,ICF,JCF,NCF)
C     MARCH, 1971
C     GIVEN THE HORIZONTAL COORDINATES OF A POINT, NEST RETURNS THE
C     NET MESH OR SUB-MESH INDEX NOATA AND THE BOUNDARY COORDINATES OF
C     THE MESH OR SUB-MESH
C     MESH INDEX IS -999 IF INFUT POINT LIES OLTSIDE ATMOS.
C     NET   - PRIMARY HORIZONTAL SPACE RESOLUTION MESH ARRAY
C     NETSU - HORIZONTAL SPACE RESOLUTION SUB-MESH ARRAY
C     XQ    → INPUT POINT > COCROINATE
C     YQ    - INPUT POINT Y COORDINATE
C     NDATA - OUTPUT MESH CR SUB-MESH INDEX
C     XL    - OUTPUT MESH OR SUB-MESH  LEFT BOUNDARY X COORDINATE
C     XR    - OUTPUT MESH CR SUB-MESH RIGHT BOUNDARY X COORDINATE
C     YL    - OUTPUT MESH (R SUB-MESH LOWER BOUNDARY Y COORDINATE
C     YU    - OUTPUT MESH OR SUB-MESH UPPER BOUNDARY Y COORDINATE
      COMMON /CNTROL/ IPOUT,ISIN,ISOUT,JPARN,MC(20),NSEQO
      COMMON/INDEX/ICX,JCX,KBHX,LTIMX,NAT,NCX,NDATX
      COMMON/SPACE/WINT,XLLC,YLLC,ZMAX,ZMIN,TIMEX
      DIMENSION NET(ICF,JCF),NETSU(NCF)
      DATA PROGRM/6HNEST  /
COMPUTE MESH INDICES IC ANC JC FOR (XQ,YQ)
      IC=(XQ-XLLC)/WINT+1.
      JC=(YQ-YLLC)/WINT+1.
COMMENCE MESH SEARCH
CHECK IF IC (JC) LIES BETWEEN 1 AND ICX (JCX)
      IF((IC.GE.1).AND.(JC.GE.1).AND.(IC.LE.ICX).AND.(JC.LE.JCX))GO TO 1
CANCEL MESH SEARCH. (XQ,YG) LIES OUTSIDE ATMOS.
      NDATA=-999
      RETURN
COMPUTE XL,XR,YL, AND YU FOR MESH
    1 VINT=WINT
      XL=VINT*FLOAT(IC-1)+XLLC
      XR=VINT*FLOAT(IC)+XLLC
      YL=VINT*FLOAT(JC-1)+YLLC
      YU=VINT*FLOAT(JC)+YLLC
CHECK SIGN OF NET(IC,JC)
      IF(NET(IC,JC)) 4,2,3
    2 CALL ERROR(PROGRM,-2,ISOUT)
CONCLUDE MESH SEARCH
    3 NDATA=NET(IC,JC)
      RETURN
COMMENCE QUADRANT SEARCH. CBTAIN POINTER NQ
    4 NQ=-NET(IC,JC)
