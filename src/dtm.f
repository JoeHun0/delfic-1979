      SUBROUTINE CNTR(NET,NETSU,NDATA,XG,YG,ICF,JCF,NCF)
C     MARCH, 1971
C     SUBROUTINE CNTR DETERMINES THE X,Y COORDINATES AT THE CENTER OF A
C     HORIZONTAL SPACE RESCLUTION  MESH OR SUB-MESH.
C     NDATA - ATMOS. HORIZ. SPACE NET MESH OR SUB-MESH INDEX
C     XG    - NET MESH OR SUB-MESH CENTER POSITION X COORDINATE
C     YG    - NET MESH OR SUB-MESH CENTER POSITION Y COORDINATE
      COMMON/CNTROL/IPOUT,ISIN,ISOUT,JPARN,MC(20),NSEQO
      COMMON /INDEX/ ICX,JCX,KBHX,LTIMX,NAT,NCX,NDATX
      COMMON /SPACE/ WINT,XLLC,YLLC,ZMAX,ZMIN,TIMEX
      DIMENSION NET(ICF,JCF),NETSU(NCF)
      DATA PROGRM/6HCNTR  /
      VINT=WINT/2.
      IG=0
      JG=0
      NDBLE=1
      NSTOR=NDATA
CCMMENCE SEARCH LOOPS FOR IC AND JC
    1 DO 2 JC=1,JCX
      DO 2 IC=1,ICX
CHECK IF NSTOR CAN BE FOUND IN NET
      IF(NET(IC,JC).EQ.NSTOR) GO TO 9
   2  CONTINUE
COMMENCE SEARCH LOOP FOR NC
      DO 3 NC=1,NCX
CHECK IF NSTOR CAN BE FOUND IN NETSU
      IF(NETSU(NC).EQ.NSTOR) GO TO 4
   3  CONTINUE
      CALL ERROR(PROGRM,-3,ISOUT)
COMMENCE TRACEBACK THROUGH POINTER SEQUENCE
    4 NG=NC-4*(NC/4)+1
      ING=+1
      JNG=-1
CONVERT NSTOR TO ITS IMMEDIATELY PRECEDING POINTER
      NSTOR=-NC+3
      GO TO (8,7,6,5), NG
    5 ING=ING+2
      NSTOR=NSTOR+1
    6 JNG=JNG+2
      NSTOR=NSTOR+1
    7 ING=ING-2
      NSTOR=NSTOR-3
COMPLTE QUORANT LABELS IG AND JG
    8 IG=IG+ING*NDBLE
      JG=JG+JNG*NDBLE
      NDBLE=2*NDBLE
      VINT=VINT/2.
CONTINUE SEARCH FOR IC ANC JC
      GO TO 1
COMPUTE XG AND YG
    9 IG=IG+NDBLE
      JG=JG+NDBLE
      XG=WINT*FLOAT(IC-1)+VINT*FLOAT(IG)+XLLC
      YG=WINT*FLOAT(JC-1)+VINT*FLOAT(JG)+YLLC
      RETURN
      END
