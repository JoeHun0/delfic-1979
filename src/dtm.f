C     SIZE CLASS.
      DOWN=(FAV*EDDY/SIGW)**2
      CROSS=1./SQRT(1.+4.*DOWN)
      DOWN=1./SQRT(1.+DOWN)
      PSZBE=PSIZ
  103 IF( MC3 .GT. 0)
     1WRITE(ISOUT,8016) NSEQ,XP,YP,ZP,TP,PMAS,RWAF,ZLOW,DWAF
