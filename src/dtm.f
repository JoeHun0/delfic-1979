C
C     SET ALL NAD(J) EQUAL TO J TO PROVIDE INDICES FOR THE FULL SET OF
C     DATA POINTS AND TO PROVIDE AN INITIAL SET OF -NEAREST- DATA POINTS
      NAD(J)=J
C
C     COMPUTE DISTANCES BETWEEN THE CURRENT LATTICE CENTER POINT
C     (XG,YG,ZG) AND EACH CF THE INPUT DATA VECTOR LOCATIONS.
C     EACH OF THE DATA VECTOR LOCATIONS
      TX=XS(J)-XG
