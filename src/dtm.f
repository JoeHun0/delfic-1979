      DIMENSION RSUM(KBHF,NDATF,LTIMF),TSUM(KBHF)
      DIMENSION XPAR(100),YPAR(100),ZPAR(100),TPAR(100),PDAM(100)
      DIMENSION PSAM(100),RWFR(100),DWFR(100),ZLWF(100),VWFR(100)
C
      DATA PROGRM/6HSPRVS / ,JF/100/
C
 8015 FORMAT( 1H+, 102X, 8HAIRBORNE)
 8016 FORMAT( 1H , I4, 8E12.4)
 8017 FORMAT(1H0,5X, 86H* * * * * SHORT-CUT TRANSPORT IS CANCELLED BECAU
     1SE VERTICAL WIND IS NON-ZERO * * * * *//)
