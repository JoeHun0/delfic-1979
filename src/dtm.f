 1002 ZLIM=ZBH(IZ+1)
 1012 IF(TMAX .LT. 0.0) TMAX=TIMEX
 1003 IF( MC3 .LT. 1) GO TO 1004
      WRITE(ISOUT,8022) FAV,H,ZLIM
      WRITE(ISOUT,8024)
 1004 CONTINUE
      IF(MC( 4 ).NE.0) GO TO 1255
COMPUTE DEPOSITION TIME FROM THE BASE OF EACH STRATUM FOR USE BY THE
