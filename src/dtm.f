      SUBROUTINE CALIB(A,NX,AN,NS,N)
C     MARCH, 1971
C     SUBROUTINE CALIB DETERMINES A JUSTIFIED INDEX WHICH RELATES AN
C     INPUT DATA POINT TO ITS CORRESPONDING POSITION IN AN INPUT ARRAY.
C
C     A     - INPUT DATA ARRAY
C     NX    - INPUT MAXIMUM INDEX OF A
C     AN    - INPUT DATA POINT
C     NS    - INDEX JUSTIFICATION CODE.   WHEN GIVEN (BY INPUT) THE
C           FOLLOWING VALUES, A IS DETERMINED SUCH THAT -
C             +1 A(N) IS .LE. AN
C             -1 A(N) IS .GT. AN
C     N     - OUTPUT INDEX
C
      DIMENSION A(NX)
      EPS = 1.E-6 * NS * ABS( AN )
      N=0
COMMENCE SEARCH FOR N
    1 N=N+1
      NN=N+(1+NS)/2
COMPARE A(NN) WITH AN ONLY IF  NN IS LESS THAN NX+1
      IF((NN.LT.NX+1).AND.(A(NN).LT.AN+EPS)) GO TO 1
      RETURN
      END
