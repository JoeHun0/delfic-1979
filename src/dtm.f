C     REMOTE OF THE SET OF -NEAREST- DATA POINTS.  NOTE THAT FOR THE 1ST
C     PASS ALL THE NN -NEAREST- POINTS ARE EQUALLY LIKELY TO BE THE MOST
C     REMOTE OF THE SET.
      NADT=1
