      SY(J) =AP(N3)*SCALE(2) * COS( RADC*(AP(N2)*SCALE(3) + TRNS))
      GO TO 100
   50 SX(J) = AP(N2) * SCALE(2)
      SY(J) = AP(N3) * SCALE(2)
      GO TO 100
  101 JTOPV=J
      IF(MC(2).EQ.1) GO TO 102
COPY OUT SCALED INPUT DATA
      IF(SPEC .EQ. WIND) WRITE( ISOUT,20)
      IF(SPEC .EQ. TURB) WRITE( ISOUT,21)
      IF(SPEC .EQ. WIND)WRITE(ISOUT, 3)(J,ZS(J),XS(J),YS(J),SX(J),SY(J),
     1 SZ(J),J=1,JTOPV)
      IF(SPEC .EQ. TURB)WRITE(ISOUT,33)(J,ZS(J),XS(J),YS(J),SX(J),SY(J)
     1 ,J=1,JTOPV)
  102 IF(NN.GT.JTOPV .OR. NN.LT. 0) NN=JTOPV
  115 IF(NN.LT.1) CALL ERROR(PROGRM,-115,ISOUT)
      WRITE(ISOUT,4)NN,JTOPV
COMMENCE CALCULATION OF DATA VECTOR AT EACH SPACE LATTICE CENTER POINT
