     1 9X, 4HPMAS, 8X, 4HRWAF, 8X, 4HZLOW, 8X, 4HDWAF/)
 8025 FORMAT( 1H1, 38X, 31HPRE-TRANSPORT PARCEL PROPERTIES/)
C
COMPUTE TURBULENCE PARAMETER AVERAGED OVER ALL SPACE, HAV
      HAV=0.
      DO 40 L=1,LTIMX
   40 HAV=HAV + HDAV(L)
      HAV=HAV/LTIMX
CHOOSE STANDARD DEVIATION OF VERTICAL TURBULENCE
      SIGW=EDDY
      IF(MC(6) .GT. 0) SIGW=5.39*(HAV)**(1.0/3.0)
      MC3=MC(3)
      IF(MC3 .GT. 0) WRITE(ISOUT,8025)
      NSEQ=0
      PSZBE=-2.0
      IF(MC( 4 ).NE.0) GO TO 47
CANCEL SHORT-CUT TRANSPORT IF VERTICAL WIND IS NON-ZERO
      DO 45 L=1,LTIMX
      DO 45 K=1,KBHX
      IF(WAVG(K,L).NE.0.0)GO TO 46
  45  CONTINUE
      GO TO 47
  46  MC( 4 )=1
      WRITE(ISOUT,8017)
  47  CONTINUE
