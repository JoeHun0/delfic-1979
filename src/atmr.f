      SUBROUTINE ATMR
C
C     H. G. NORMENT, ATMOSPHERIC SCIENCE ASSOCIATES - DECEMBER 1978
C
C
C     ATMR READS IN ATMOSPHERE TABLES
C
C     ATMOSPHERE TABLE GLCSSARY- UNITS ARE FOR THE SCALED ENTRIES
C
C   1   ALT - ALTITUDE ABCVE MSL (METERS)
C   2   ATP - TEMPERATURE (DEGREES KELVIN)
C   3   PRS - PRESSURE (PASCALS)
C   4   RLH - RELATIVE HUMIDITY (PERCENT)
C   5   RHO - DENSITY (KGM/M**3)
C   6   ETA - VISCOSITY (KGM/(M-SEC))
C
C   KATM=IC(4) IS THE ATMOSPHER DATA PRINT CONTROL
C
C
      COMMON /ATMOS/ NAT, ALT(256),  ATP(256),  PRS(256), PLH(256),
     1        RHO(256), ETA(256), NHODO, ZV(100),  VX(100), VY(100)
      COMMON /CONTRL/ DETID(12),IC(20),IRAU,IRISE,ISIN,ISOUT;JPARN,KDI
C
      DIMENSION FMT(12),SCALE( 8),ATMSUB(6),ATMZKO(6),ATMMAX(6),AP(6)
      DIMENSION ATIO(12)
      DATA PROGRM/6H ATMR /, ALIMIT/999999./
      DATA ATMSUB/-1J00.,294.65,.1139E6,77.,1.347,.18206E-4/
      DATA ATMZRO/ 0.0,288.15,.10133E6, 77.,1.2250,.17894E-4/,
     1ATMMAX/50000.,270.65,.79779E2,4.0,.10269E-2,.17037E-4/
C
   2  0FORMAT(20I4                                                     )
   30 FORMAT(12 A                                                      6
   40 FORMAT(8F10.0                                                    )
   44 FORMAT(1H1)
   46 FORMAT( 20X,20HATHOSFHERE IDENTIFICATION - 12A6//)
   47 FORMAT(  37X,10HATMCSPHERE,51X//7X,3HALT,11X,3HATP,11X,3HPRS,11X,3
     1HRLH,11X,3HRHO,11X,3HETA)
   48 FORMAT( /(6(2X,E12.5)))
C
C
      READ(ISIN,30)ATIO
      KATM = IC(4)
      IF(KATH .GT. 0) WRITE(ISCUT,44)
      WRITE(ISOUT,46)ATID
      IGO=0
      NBRNCH=1
      WATCOR=(1.-18./29.)/100.
C
C     READ OBJECT-TIME FORMAT
C
      READ(ISIN,30)FMT
C
C     READ SCALE AND ADJUSTMENT FACTORS
C
      READ(ISIN,40)SCALE
      00 90 I=1,6
      IF(SCALE(I))90,91,90
   91 SCALE(I)=1.
   90 CONTINUE
C
C     READ ATMOSPHERE DATA SEQUENCE INDICIES
      READ(ISIN,20)N1,N2,N3,N4,N5,N6
C
C\mathcal{C} READ ATMOSPHERE TABLE ENTRIES, SEQUENCE AND ADJUST THEM TO
C     PROPER UNITS, AND WHERE APPROPRIATE COMPUTE THOSE ENTRIES NOT
C     PROVIDED IN THE INPUT.   ETA NEED NOT BE INPUT.  EITHER PRS OR RHZ
C     (BUT NOT BOTH) NEEDS TO BE INPUT.
C
      I=0
  100 READ(ISIN,FMT)AP
      IF(AP(N1) .GE. ALIMIT) GO TO 105
      I = I+1
      ALT(I)=(AP(N1)+SCALE(7))*SCALE(1)
      ATP(I)=(AP(N2)+SCALE(8))*SCALE(2)
      PRS(I)=AP(N3)*SCALE(3)
      RLH(I)=AP(N4)*SCALE(4)
      RHO(I)=AP(N5)*SCALE(5)
      ETA(I)=AP(N6)*SCALE(6)
C
C     ARE SUCCESSIVE TABLE ENTRIES IN ORDER OF INCREASING ALTITUDE-
C
      IF(I.EQ.1) GO TO 70
      IF (ALT(I)-ALT(I-1)) 45,45,70
   45 IRROR=-45
      WRITE(ISOUT,40) ALT(I), ALT(I-1)
      GO TO 130
   70 IF(ETA(I) .GT.0.0) GC TO 1070
      ETA(I)=1.458E-6*ATP(I)**1.5/(110.4+ATP(I))
 1070 IF(PRS(I).GT.0.0) GO TO 73
      IF(RHO(I).GT.0.0) GC TO 72
   71 IRROR=-71
      GO TO 130
   72 ES= 611.*(273./ATP(I))**5.13* EXP(25.*(ATP(I)-273. )/ATP(I))
      PRS(I)= 286.79* RHO(I)*ATP(I) +ES*RLH(I)*WATCOR
      GO TO 100
   73 IF' HO(I).GT.0.0) GO TO 100
      ES= 611.*(273./ATP(I))**5.13* EXP(25.*(ATP(I)-273. )/ATP(I))
      RHO(I)= (PRS(I)-ES*RLH(I)*WATCOR)/(286.79*ATP(I))
      GO TO 100
C
  1^5 NAT=I
C
C     DETERMINE IF THE TABLE MUST BE EXPANDED TO 256 ENTRIES
C
  110 IF(NAT -256)140,111,120
C
C 111 THE TABLES DO NOT NEED EXPANSION.  CHECK TO DETERMINE IF THE
C     THE PROPER BOUNDARIES ARE NOT THE PROPER BOUNDARIES.
C
  111 IF(ABS(ALT(1)+ 1000.).LE.1.) GO TO 113
  112 IRROR=-112
      GO TO 130
  113 IF(A3S(ALY(256)-5.E4).LE.5).) GO TO 115
  114 IRROR=-114
      GO TO 133
C
C 115 THE TABLES HAVE THE PROPER BCUNDRIES.  CHECK TO CETERMINE IF THE
C     ALTITUDE INTERVALS ARE ALL.200 METERS.
C
  115 00 116 I=2,256
      IF(ABS(ALT(I)-ALT(I-1)-200.).GT.2.) IF(NBRNCH-1) 140,140,137
  116 CONTINUE
      GO TO 270
  120 IRROR=-120
  130 CALL FRROR(PROGRM,IRROR,ISOUT)
  137 IRF   -137
      GO    130
C
C 140 THE TABLES NEED EXPANSION OR INTERVAL ADJUSTMENT
C
  140 REWIND IRISE
C
C     DO THE TABLES BEGIN AT -10J0 METERS-
C     IF NOT MAKE AN ENTRY AT -1000 METERS FROM THE ARDC STANDARD ATMOS.
C
      IF(A9S(ALT(1)+1000.) .GT. 1.) GO TO 150
      ALT(1)=-1000.
      GO TO 200
  150 WRITE(IRISE)ATMSUB
  160 IGO=IGO+1
C
C     CO THE TABLES HAVE AN ENTRY AT     0 METERS-
C     IF NOT MAKE AN ENTRY AT     0 METERS FROM THE ARDC STANDARD ATMOS.
C
      IF(ALT(1)   .LE. 0.0(1)GO TO 200
      WRITE(IRISE)ATMZRO
      IGO=IGO+1
C
C     STORE THE INPUT TABLES ON TAPE
C
  200 DO 210 I=1,NAT
  210 WRITE(IRISE)ALT(I),ATP(I),PRS(I),RLH(I),RHO(I),ETA(I)
C
C     DO THE TABLES HAVE AN ENTRY AT 5.000 METERS-
C     IF NOT MAKE AN ENTRY AT 5J.U. METERS FROM THE ARCC STANDARD ATMOS.
C
      IF(ALT(NAT ) .GE. 5.E4) GO TO 220
      IF(A9S(ALT(NAT )-5.E4).LE.50.)GO TO 220
      WRITE(IRISE)ATMMAX
      NAT=NAT+1
C
C     INITIALIZE FOR THE TABLES EXPANSION
C
  220 REWIND IRISE
      NAT=NAT+IGO
      IF(NAT -256)222,222,221
  221 IRROR=-221
      GO TO 139
  222 DALT=200.
      NA=1
      READ(IRISE)ALT(1),ATP(1),PRS(1),RLH(1),RHO(1),ETA(1)
      A1=ALT(1)
      A2=ATP(1)
      A3=PRS(1)
      A4=RLH(1)
      A5=RHO(1)
      A6=ETA(1)
C
C     EXPAND THE TABLES TO 256 ENTRIES IN 200 METERS INTERVALS IN
C     ALTITUDE FROM -1000 TO 50000 METERS BY LINEAR INTERPOLATION
C     FROM THE  INPUT TABLES
C
      00 260 I=2,256
      ALT(I)=ALT(I-1)+DALT
  225 IF(A1.GE.ALT(I))GO TO 250
      IF(ALT(I)-A1 .LT. 2.) GO TO 250
      NA=NA+1
      IF(NAT - NA .GE.()GC TO 240
  230 IRROR=-230
      GO TO 130
  240 READ(IRISE)A1,A2,A3,A4,A5,A6
      GO TO 225
  250 TERP=  DALT     /(A1-ALT(I-1))
      ATP(I)=ATP(I-1)+TERF*(A2-ATP(I-1))
      PRS(I)=PRS(I-1)+TERP*(A3-PRS(I-1))
      RLH(I)=RLH(I-1)+TERP*(A4-RLH(I-1))
      RHO(I)=RHO(I-1)+TERP*(A5-RHO(I-1))
      ETA(I)=ETA(I-1)+TERP*(A6-ETA(I-1))
  262 CONTINUE
      NAT=256
      NBRNCH=2
      GO TO 111
  27? IF(KATM .EQ. 0) RETURN
      WRITE(ISOUT,47)
      WRITE(ISOUT,48 )(ALT(I),ATP(I),PRS(I),RLH(I),RHC(I),ETA(I),
     1   I=KATM,NAT,KATM)
      RETURN
      END
