      SUBROUTINE ICM
C
C     H. G. NURMENT, ATMOSPHERIC SCIENCE ASSOCIATES - DECEMBER 1978
C
C
C     PROGRAM TO DETERMINE THE INITIAL CONDITIONS SPECIFICATIONS OF
C     TIME, TEMPERATURE, TOTAL SOIL MASS, FRACTION OF THE SOIL BURDEN IN
C     THE VAPOR PHASE, ANC THE SIZE FREQUENCY DISTRIBUTION OF THE
C     CONDENSED PHASE SOIL OR AIRBURST PARTICLES.  IT ALSO PRINTS A
C     HEADING AND PRINTS THE CRITICAL DATA.
C
C
      COMMON /BASIC/ W,FW,ZBRSTZ,HEIGHT,ZSCL,SLUTMP,TMSD,XGZ,YGZ,TGZ
      COMMON /CONTRL/ DETID(12),IC(20),IRAD,IRISE,ISIN,ISOUT,JPARN,KDI
      COMMON /INITL/ F, PHI, SSAM, TME, TMPG, TMPS, VPR
      COMMON /PARTCL/ NOSTR,RHCP,OMEAN,SD,PS(200),DIAM(201),FMASS(200)
      EQUIVALENCE (DMEAN,CAYM),(SD,EXPO)
C
      DATA PROGRM /6H ICH  /
C
C
   1  FORMAT(12A6)
   2  FORMAT( /3X, 60HTHE SPECIFIED STANDARD DEVIATION IS NEGATIVE HENCE
     1 INCORRECT////
   3  FORMAT(8F10.0)
   4  FORMAT( //25X, 28H****  BASIC PARAMETERS  ****/ 20X, 24HYIELDS - T
     TOTAL (FISSION), 21X, E12.5, 2H (L12.5, 4H) KT/ 20X, 24HHEIGHT OR D
     2EPTH OF BURST, 21X, E12.5, 2X, 6HMETERS, 2H (E12.5, 21H FEET) KELA
     3TIVE TO GZ/ 20X, 14HALTITUDE OF GZ, 31X E12.5, 7H METERS/ 20X,
     4 13HSOIL CATEGORY)
 5    FORMAT(1H+,65X,9HSILICEOUS)
 6    FORMAT(1H+,65X,10HCALCAREOUS)
 7    FORMAT( /20X,             36HPARTICLE SIZE FREQUENCY DISTRIBUTION/
     125X32HA LOG-NORMAL DISTRIBUTION WITH -/30X,15HMEDIAN DIAMETER,20X,
     2E12.5,2X,11HMICROMETERS/30X,28HGEOMETRIC STANDARD DEVIATION, 7X,
     3E12.5/25X, 34HTHIS DISTRIBUTION WAS SPECIFIED BY)
 8    FORMAT(1H+,65X,11HTHE PROGRAM)
 9    FORMAT(1H+,65X,8HTHE USER)
 10   FORMAT(20I4)
 11   FORMAT(/3X,58HTHE SCALED DEPTH OF BURST IS BEYONC THE SCOPE OF THE
     1 MODEL)
   12 FORMAT( 1H+, 65X, 36HNOT APPLICABLE.  THIS IS AN AIRBURST)
 13   FORMAT( //25X37H****  INITIAL CLOUD PROPERTIES AT H +E12.5,14H SEC
     10NDS  ****/ 20X,23HAVERAGE GAS TEMPEKATURE38X,E12.5,2X,14HDEGREES
     2KELVIN/ 20X,56HAVERAGE TEMPERATURE OF CONDENSED PHASE MATERIAL IN
     3CLOUD,5X,E12.5,2X,14+DEGREES KELVIN/ 20X,31HMASS OF VAPORIZED SOIL
     4 IN CLOUD,30X,E12.5,2X,9HKILOGRAMS/ 20X41HMASS CF CONDENSED PHASE
     5MATERIAL IN CLOUD,20X,E12.5,2X,9HKILOGRAPS)
 14   FORMAT( //25X37H****  INITIAL CLCUD PROPERTIES AT H +E12.5.14H SEC
     10NDS  ****/ 20X,23HAVERAGE GAS TEMPERATURE38X,E12.5,2X,14HDEGREES
     2KELVIN/                             20X41HMASS OF CONDENSED PHASE
     3MATERIAL IN CLOUD,20X,E12.5,2X,9HKILOGRAMS)
 15   FORMAT(1X,11HLEAVING ICM)
   16 FORMAT( 1H1,   50X, 19H* * * * * * * * * *//55X,11HD E L F I C//
     1                                            12X,101HT H E   D E P
     2A R T M E N T   O F   D E F E N S E   F A L L C L T   P R E D I C
     3T I O N   S Y S T E M//51X19H* * * * * * * * * *////43X,  36HINITI
     4ALIZATION AND CLOUD RISE MODULE///  55X, 11HPREPARED BY/ 46X,  30H
     5ATMOSPHERIC SCIENCE ASSOCIATES/  54X, 14HBEDFORD, MASS.////25X,
     630H****  RUN IDENTIFICATION  ****, 3X, 12A6)
 17   FORMAT(/3X,60HTHE SPECIFIED MEAN PARTICLE SIZE IS NEGATIVE HENCE I
     1NCORRECT///)
   18 FORMAT(1H0, 9X, 89HPARTICLE SIZE DISTRIBUTION SUPPLIED IN TABULAR
     1FORM BY THE USER (DIAMETERS ARE IN METERS))
  19  FORMAT( 20X, 24HFALLCUT PARTICLE DENSITY, 21X, E12.5,  8H KG/M**3)
  20  FORMAT( 20X, 23HSCALED HEIGHTS OF BURST, 3AX, E12.5, 7H FEET (,
     1 E12.5, 8H METERS))
   24 FORMAT( /20X,           38HPARTICLE VOLUME FREQUENCY DISTRIBUTION/
     125X32HA LOG-NORMAL DIST RIBUTIO NWIT H-/30X,15HMEDIA NDIAMETER,20X
     2E12.5,2X,11HMICROMETERS/30X,28HGEOMETRIC STANDARC DEVIATION, 7X,
     3E12.5)
   25 FORMAT(1H09X,65HPARTICLE SIZE - MASS DISTRIBUTION TABLE (DIAMETERS
     1 ARE IN METERS))
   26 FORMAT(/22X77H****  THE CONTROL VARIABLE ARRAY, IC(J), WAS GIVEN T
     1HE FOLLOWING VALUES  ****/ 19X, 20I4)
   27 FORMAT(/20X, 36HPARTICLE MASS FREQUENCY DISTRIBUTION/ 25X, 31HA PO
     1WER-LAW DISTRIBUTION WITH -/ 30X, 15HK-TO-MASS RATIO, 20X, 2PE12.5
     2/ 30X, 21HEXPONENTIAL PARAMETER, 14X, 1PE12.5)
   28 FORMAT(1H0, 11X, 63HTHE PARTICLE DISTRIBUTION ABCVE IS A SIZE-ACTI
     1VITY DISTRIBUTION)
 192  FORMAT(//51X,19H* * * * * * * * * *//)
  193 FORMAT( 10X, 33HNUMBER OF PARTICLE SIZE CLASSES =15/
     1    1H0,20X, 8HDIAMETER, 4X,13HLOWER BOUNDRY, 5X, 8HFRACTION,
     2 5X,14HUPPER BOUNDARY/)
  194 FORMAT(12X,I3,4(3X,E12.5))
  195 FORMAT(2F10.0)
  198 FORMAT(/3X,56HTHE PARTICLE SIZE DISTRIBUTION TABLE IS IMPROPERLY 0
     2RDERED///)
 1400 FORMAT(                                            20X, 73HFRACTIO
     1N OF THE TOTAL EXPLCSION ENERGY IN THE CLOUD AT THE INITIAL TIME =
     2FG.4/  20X. 51HFRACTION CF THIS ENERGY USED TO HEAT AIR AND SOIL =
     3F6.4/  20X, 37HFRACTION  USED TO HEAT LIQUID WATER =F6.4/
     4                                             20X, 37HFALLOUT SOLID
     5IFICATION TEMPERATURE = F8.3,  4H (K))
 1700 FORMAT(1HD19X30HCLOUT SUBDIVISION PARAMETERS -/  23X, 52HNUMBER OF
     1 CLOUD SUBDIVISIONS IN THE VERTICAL (KDI) =I4/  23X, 48HPARCEL HOR
     2IZONTAL SUBDIVISION PARAMETER (IRAD) =I4)
 1800 FORMAT(
     120X22HDETONATION COORDINATES,10X,3HXGZ,13X,3HYGZ,13X,3HTGZ/
     244X.3(E13.6.3X))
C
C
C
C     READ RUN IDENTIFIER
      READ (ISIN,1)DETIO
C     READ CONTROL PARAMETERS
      READ(ISIN,10) IC
C
C     WRITE OVERALL TITLE
      WRITE (ISOUT,16)DETID
      WRITE(ISOUT,26) IC
C     READ IN BASIC DATA
      READ(ISIN,3)W, FW, HEIGHT, ZBRSTZ, SLDTMP, PHI
      IF(SLOTMP .EQ. 0.0  .AND.  IC(2) .EQ. 0) SLOTMP=2200.
      IF(SLOTMP .EQ. 0.0  .AND.  IC(2) .EQ. 1) SLOTMP=2800.
   40 IF(SLOTMP .LE. 0.0) CALL ERROR(PROGRM, -40, ISOUT)
      IF(PHI .EQ. 0.0) PHI=1.0
      READ(ISIN,10)NOSTR,KCI,IRAD
      IF( NOSTR .EQ. 0 ) NOSTR=100
      IF(KOI .EQ. 0) KOI=15+ALOG(W)
      READ(ISIN,3)XGZ,YGZ,TGZ
      IF(IC(1)-1)210,220,230
C 210 A LOGNORMAL PARTICLE DISTRIBUTION IS SPECIFIED
  210 READ(ISIN,3) DNS, OMEAN, SD
C     IS A LOGNORMAL DISTRIBUTION SPECIFIED BY THE USER
      IS=0
      IF(DMEAN.GT. 0.0) IS=1
      GO TO 23
C 220 A POWER-LAW PARTICLE DISTRIBUTION IS SPECIFIED
  220 READ(ISIN,J)ONS, CAYM, EXPO
      GO TO 23
C 230 A TABULAR PARTICLE DISTRIBUTION IS SPECIFIED
  230 READ(ISIN,3)DNS
      READ(ISIN,195)(DIAM(I),FMASS(I),I=1,NOSTR)
      LD=NOSTR+1
      READ(ISIN,195)DIAM(LC)
C
C     CHECK ORDERING OF THE HISTOGRAM TABLE
      DO 215 I=2,LD
      IF(DIAM(I) .LT. DIAM(I-1)) GO TO 215
      WRITE( ISOUT,198)
      GO TO 200
  215 CONTINUE
   23 HO8 =  HEIGHT/0.3048
      IF( DNS .EQ. 0.0 ) DNS = 2.6
      RHOP=ONS*1000.
C     ZSCL IS THE SCALED HCB  -  008
      ZSCL = HOB /((W)**(1.0/3.4))
C
C     TEST THE SCALED HOB TO DETERMINE IF  SUBSURFACE, LOW AIRBURST
C     OR PURE AIRBURST
      IF(ZSCL+20.0 .LT. 0.0) GO TO 143
      IF(ZSCL .LT. 180.0) GO TO 70
      CALL AIRBRS
      GO TO 95
 70   CALL TIMEE
      CALL TEMP
      CALL MASS
      CALL VAPOR
      IF(JC(1)-1)90,95,95
C
C     TEST FOR ACCEPTABLE SPECIFICATIONS OF LOGNORMAL PARTICLE SIZE
C     DISTRIBUTION
 90   IF(SD)91,92,92
 91   WRITE (ISOUT,2)
      GO TO 200
   92 IF(OMEAN)94,95,95
 94   WRITE (ISOUT,17)
      GO TO 200
C
C     COMPUTE PARTICLE SIZE-VOLUME (MASS) FREQUENCY HISTOGRAM
 95   CALL DSTBN
      SSAM = SSAM - VPR
C     PRINT INITIAL CONDITIONS RESULTS
      WRITE(ISOUT,4)W,FH, FEIGHT,HOB,ZBRSTZ
      IF( ZSCL .LT. 180. ) IF(IC(2))301,301,302
      WRITE(ISOUT,12)
      WRITE( ISOUT, 14 ) TME, TMPG, SSAM
      GO TO 118
 301  WRITE (ISOUT,5)
      GO TO 108
 302  WRITE (ISOUT,6)
 108  WRITE(ISOUT,13)TME,TMPG,TMPS,VPR,SSAM
  118 ZSCM=ZSCL*0.3048
      WRITE(ISOUT,20)ZSCL,ZSCH
C     SET FRACTION OF EXPLOSION ENERGY IN THE CLOUD
      F=.45
      RPHI=1.0-PHI
      WRITE(ISOUT,1400) F,PHI,RPHI,SLDTMP
      WRITE(ISOUT,1800)XGZ,YCZ,TGZ
      WRITE(ISOUT,19) RHOF
      IF(IC(1)-1)309,310,311
  309 WRITE(ISOUT,7)DHEAN,SD
      IF (IS)102,103,102
 103  WRITE (ISOUT,8)
      GO TO 105
 102  WRITE (ISOUT,9)
  105 BARNU = EXP(ALOG(DMEAN) + 3.0*ALOG(SD)**2)
      WRITE(ISOUT,24)BARMU,SD
      WRITE(ISOUT,25)
      GO TO 315
  310 WRITE(ISOUT,27) CAYM, EXPO
      GO TO 315
  311 WRITE(ISOUT,18)
C     PRINT PARTICLE SIZE DISTRIBUTION TABLE
  315 WRITE(ISOUT,193)NOSTR
      00 602 J=1,NOSTR
  602 WRITE(ISOUT,194)J,PS(J),DIAM(J+1),FMASS(J),DIAM(J)
C     CHECK IF PARTICLE DISTRIBUTION IS OF THE SIZE-ACTIVITY TYPE
      IF(IC(5) .EC. 0) GO TO 603
      SD=-1.0
      WRITE(ISOUT,28)
  603 WRITE(ISOUT,1700)KCI,IRAD
      WRITE(ISOUT,192)
  200 WRITE(ISOUT,15)
      RETURN
 143  WRITE (ISOLT,11)
      GO TO 200
      END
