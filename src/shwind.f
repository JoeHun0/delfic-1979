      SUBROUTINE SHWIND
C
C     H. G. NORMENT, ATMOSPHERIC SCIENCE ASSOCIATES - DECEMBER 1978
C
C
C     READS IN SHOT TIME WIND DATA ABOVE GROUND ZERO
C     THESE WINDS ARE USDE TO COMPUTE WIND SHEAR EFFECTS ON CLOUD RISE
C     AND TO TRANSPORT THE CLOLO AND FALLOUT WHILE THE CLOUD RISES AND
C     STABILIZES.
C
C
       COMMON /ATMOS/ NAT, ALT(256),  ATP(256),  PRS(256), RLH(256),
     1        RHO(256), ETA(256), NHODO, ZV(100),  VX(100), VY(100)
      COMMON /CONTRL/ DETIO(12),IC(20),IRAU,IRISE,ISIN,ISOUT,JPARN,KOI
C
      INTEGER FORM,METEOR,RESOLV
      DIMENSION SCALE(5),AP(3),FMT(12)
      DATA ALIMIT  , RADC      , PROGRM  , METEOR , RESOLV
     1  /  999999. ,.0174532925, 6HSHWIND, 4HMETE , 4HRESO /
C
    1 FORMAT(20I4)
    2 FORMAT( 1H1, 37X, 19+SHOT-TIME WIND DATA// 19X, 8HRAW DATA, 36X, 1
     14HPROCESSED DATA// 8X, 1HZ, 9X, 10HVX OR DIR., 3X, 11HVY OR SPEED,
     2 14X, 1HZ, 12X, 2HVX, 12X, 2HVY/)
    3 FORMAT( 3(2X,1PE12.5))
    4 FORMAT( 1H+, 47X, 3(2X,1PE12.5))
    5 FORMAT( 1H0, 9X, 39HSHOT-TIME WINDS HAVE NOT BEEN SPECIFIED)
    6 FORMAT( 8F10.0)
    7 FORMAT( 12A6)
   8  FORMAT(6X, A4)
C
C
      NHODO=0
      TRNS=0.
COPY IN DATA TYPE INDICATOR AND FORMAT
      READ(ISIN,8) FORM
      READ(ISIN,7) FMT
      WRITE(ISOUT,2)
COPY IN WIND DATA SCALE FACTORS AND DATA POINTERS
      READ(ISIN,6) SCALE
      READ(ISIN,1) N1, N2, N3
      00 9 I=1,3
   9  IF( SCALE(I) .EQ. 0.0 ) SCALE(I) = 1.0
      IF(FORM .EQ. METEOR) TRNS=SCALE(3)*SCALE(5) - 185.
COPY IN WIND DATA
  100 READ(ISIN,FMT)AP
      IF(AP(N1) .GE. ALIMIT) GO TO 200
      NHODO = NHODO+1
COPY OUT RAW WIND DATA
      WRITE(ISOUT,3)AP(N1), AP(N2), AP(N3)
  10  IF(NHODO .GT. 100) CALL ERROR( PROGRM, -10, ISCUT)
COMPUTE SCALED WIND DATA
      7V(NHODO) = ( AP(N1)   + SCALE(4))*SCALE(1)
      IF(FORM .EQ. RESOLV) GO TO 15
      VX(NHODO)=AP(N3)*SCALE(2)*SIN(RADC*(AP(N2)*SCALE(3) + TRNS))
      VY(NHODO)=AP(N3)*SCALE(2)*COS(RADC*(AP(N2)*SCALE(3) + TRNS))
      GO TO 50
  15  VX(NHODO)=AP(N2)*SCALE(2)
      VY(NHODO)=AP(N3)*SCALE(2)
COPY OUT SCALED WIND DATA
   50 WRITE(ISOUT,4)ZV(NHODO),VX(NHODO), VY(NHODO)
      GO TO 100
  240 IF(NHODO .GT. 3) RETURN
      WRITE(ISOUT,5)
      RETURN
      END
