      SUBROUTINE TIMEE
C
C     H. G. NORMENT, ATMOSPHERIC SCIENCE ASSOCIATES - DECEMBER 1978
C
C
C     SETS TIME (RELATIVE TO DETONATION) OF THE INITIAL CONDITIONS
C     SPECIFICATIONS
C
C
      COMMON /BASIC/ W,FW,ZBRSTZ,HEIGHT,ZSCL,SLDTMP,TMSD,XGZ,YGZ,TGZ
      COMMON /INITL/ F, PHI, SSAM, TME, TMFG, TMFS, VFR
C
C
      Q=ZSCL*W**(-.03921)
      T2M=0.037*((0.045/0.037)**(Q/180.))*(W**(0.49-(0.07*Q/180.)))
      TME=(56.0*T2M)/(W**(0.3))
      RETURN
