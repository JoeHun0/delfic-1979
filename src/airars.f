      SUBROUTINE AIRBRS
C
C     H. G. NORMENT, ATMOSPHERIC SCIENCE ASSOCIATES - DECEMBER 1978
C
C
C     COMBINES FUNCTIONS OF SUBROUTINES TIME, TEMP, MASS, AND VAPOR
C FOR AN AIRBURST. ALSO SETS LOGNCRMAL DEBRIS PARTICLE SIZE
C     DISTRIBUTION PARAMETERS FOR AN AIRBURST.   A GEOMETRIC STANDARD
C     DEVIATION OF 2.0 IS ASSUMED.   THE MEDIAN PARTICLE DIAMETER WAS
C     COMPUTED FROM EQS. (43) AND (44) OF NATHANS,ET AL., JGR75, 7565
C     (1971) (FOR BROWNIAN MOTION)
C
C
      COMMON /BASIC/ W,FW,ZBRSTZ,HEIGHT,ZSCL,SLDTMP,TMSD,XGZ,YGZ,TGZ
      COMMON /CONTRL/ DETID(12),IC(20),IRAD,IRISE,ISIN,ISOUT,JPARN,KDI
      COMMON /INITL/ F, PHI, SSAM, TME, TMPG, TMPS, VPR
      COMMON /PARTCL/ NDSTR,RHCP,OMEAN,SD,PS(260),DIAM(201),FMASS(200)
C
C
C     SET TIME OF THE SECOND THERMAL MAXIMUM AND THE DELFIC INITIAL
C     TIME (SEC)
C
      T2M = 0.045 * W**(0.42)
      TME = 56. * T2M * W**(-0.30)
C
C     SET INITIAL CLOUD TEMPERATURE
C
      A = 6847. * W**(-0.0131)
      B = -0.4473 * W**(0.0436)
      TMPG = A * (TME / T2M)**B + 1500.
      TMPS = TMPG
C
C SET MASS OF CONDENSEC PHASE MATERIAL IN THE CLOLC (KG)
      SSAM = 90.718
      VPR = 0.0
      IF(IC(1) .NE. 0  .OR.  DMEAN .NE. J.0) RETURN
C
C     SET DE9RIS PARTICLE SIZE DISTRIBUTION PARAMETERS
C
      SD = 2.0
      DMEAN = 0.15
      RETURN
      END
