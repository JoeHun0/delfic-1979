      SUBROUTINE RSXP
C
C     H. G. NORMENT, ATMOSPHERIC SCIENCE ASSOCIATES - DECEMBER 1978
C
C
C     AFTER THE DYNAMIC CLOUD RISE HAS BEEN COMPLETED, RSXF PASSES
C     THROUGH THE RISE HISTORY TABLE, CX, TO RESIMULATE THE RISE FOR THE
C     PURPOSE OF DEFINING A DISTRIBUTION IN SPACE ABOVE GZ OF FALLOUT
C     PARCELS THAT ARE TO BE TRANSPORTED DOWNWIND BY SUBSEQUENT MODULES.
C     RESULTS ARE WRITTEN CN TAPE IRISE.
C
C
C     OPST(1,M8T)  TIME
C     DPST(2,MBT)  ALTITUDE OF  PARCEL   CENTER OF MASS
C     OPSi(3,MBT)  RADIUS
C     DPST(4,MBT)  PARTICLE DIAMETER MICROMETERS
C     OPST(5,MBT)  MASS OF ACTIVITY FRACTION
C     DPST(6,MBT)  PARCEL THICKNESS
C     OPST(7,MBT)  ALTITUDE OF PARCEL BASE
C     OPST(8,MBT)  PARCEL VOLUME
C
C
       COMMON /ATMOS/ NAT, ALT(256),  ATP(256),  PRS(256), RLH(256),
     1        RHO(256), ETA(256), NHODO, Z'(100),  VX(100), VY(100)
      COMMON /BASIC/ W,FW,ZBRSTZ,HEIGHT,ZSCL,SLDTMP,TMSD,XGZ,YGZ,TGZ
      COMMON /CONTRL/ DETID(12),IC(20),IRAD,IRISE,ISIN,ISOUT,JPARN,KDI
      COMMON /INITL/ F, PHI, SSAM, TME, TMPG, TMPS, VPR
      COMMON /PARTCL/ NDSTR,RHOP,DMEAN,SD,PS(200),DIAM(201),FMASS(200)
      COMMON /TABLES/ MCX, CX(50,10), GDPST(10,100)
C
      DIMENSION DPST(8,2),CPX(2,50),VISCX(50),PPST(8,10),DNWAF(2)
C
  444 FORMAT(*1*/10X,*DEPOSIT INCREMENTS*//15X,*TIME*,7X,*ALT*,8X,*RAD*,
     17X,*DIAM*,8X,*MASS*,8X,*OZ*,7X,*ZLOW*,7X,*VOL*//)
  666 FORMAT(1X,1PE11.3,7E11.3,I2,5X,I2,*IN CLOUD*)
  777 FORMAT(1X,1PE11.3,7E11.3,I2,5X,I2)
  888 FORMAT(1X,1PE11.3,7E11.3/1X,*SUBDIVISION*,2X,I5,5X,*SIZE CLASS*,2X
     1.15/)
C
C
C     INITIALIZE WAFER UP-CRIFT INTERPOLATION ARRAYS AND WAFER DATA
C     ARRAYS
C
      00 2 KA=1，50
      00 2 K9=1,2
    2 DPX(KB,KA)=0.0
      DO 3 KC=1,8
      DO 3 KQ=1,2
    3 DPST(KC,KQ)=0.0
    4 KDPST=KDI
      DPSTK=KDPST
C
C     COMPUTE WAFER UP-DRIFT INTERPOLATION ARRAYS
C
    6 00 7 KD=1.MCX
      IF(CX(KD,7)-CX(KD,6))53,53,54
   53 DPX(1,KD)=0.0
      GO TO 55
   54 DPX(1,KD)=(CX(KD,7)-CX(KD,6))/(CX(KD,4)-CX(KD,3))
   55 IF(CX(KD,6))56,56,57
   56 DPX(2,KD)=0.0
      GO TO 7
   57 DENOM=CX(KD,3)-ZBRSTZ
      IF(DENOM)58,56,58
   58 DPX(2,KD)=CX(KD,6)/DENOM
    7 CONTINUE
      IF(IC(6) .GT. 0) WRITE(ISOUT,444)
C
C     SET NOMINAL WAFER EDGE LENGTH IF WAFER RADII ARE TO BE SUBDIVIDED
C
      IF(IRAD)78,78,79
   76 87=0.
      GO TO 77
   79 BZ=CX(MCX,5)/FLOAT(IRAD)
C     INITIALIZE TAPE IRISE
   77 REWIND IRISE
 7882 BZ2=8Z/2.0
  120 LOOD=0
C
C     COMPUTE IN-CLOUD AIR VISCOSITIES
C
      00 6045 J=1,MCX
 6C45 VISCX(J)=1.458E-6*CX(J,9)**1.5/(110.4+CX(J,9))
      KCX=MCX-1
C
C     COMPUTE A SETTLING RATE THRESHOLC, SRTHS.  SETTLING  RATES LESS
C     THAN THIS VALUE ARE CONSIDERED INSIGNIFICANT AND ARE REPLACED
C     WITH ZERO.
C
      SRTHS = 0.1 * ( CX( MCX,4 ) - CX( MCX,3 ))/DFSTK/600.
C
C     ENTER OUTSIDE WAFER CALCULATION LOOP.  THIS LOOP DEFINES PARTICLE
C     SIZE CLASSES.
C
  200 DO 278 MA=1,NDSTR
      KOPS=2*KDPST
C
C
E     NTERM IDDLEW AFEPC ALCULATIONL OOP.T  HIS1 .00P CEFINES CLOUD
C     WAFER SUBDIVISIONS.
C
      DO 258 MB=1,KDPS
C
C     COMPUTE WAFER TOP OR BOTTOM INDICATOR, MBT
C         IF MB IS 00D, MBT=2       THIS SPECIFIES A WAFER BOTTOM
C         IF MB IS EVEN, MET=1      THIS SPECIFIES A WAFER TOP
C
      MBT=2*((MB+1)/2)-MB+1
C
C     INITIAL DPST VARIABLES
C
      DPST(1,MBT)=CX(1,1)
      DPST(3,MBT)=CX(MCX,5)
      GO TO (202,201),MBT
  2C1 OP3T(4,M3T)=DIAM(MA)
      GO TO 2J3
  202 DPST(4,MBT)=DIAM(MA+1)
  203 DPST(5,MBT)=FMASS(MA)/DPSTK
      IF(SO .GT. 0.C)DPST(5,MBT)=DPST(5,MBT)*SSAM
      BM=M3/2
      DPST(2 ,MBT)=CX(1,3)+(CX(1,4)-CX(1,3))/KDI*BM
      ZLST=OPST(2,MBT)
      KBASE=1
      J9ASE=1
C
C     ENTER.INSIDE WAFER CALCULATION LOOP. THIS LOOP DEFINES CLOUD
C     PISE HISTORY TIMES IN THE CX ARRAY
C
C
C     COMPUTE OPST TRAVEL
C
      DO 238 MC=1,KCX
      ZVSB=DPST( 2,MBT)-CX(MC,3)
      IF( ABS( ZVSB ) .LT.   .1 ) ZVSB = 0.0
      IF(ZVS8)204,210,210
  204 GO TO (206,208),KBASE
C
C     ADJUST DPST RADIUS AND ALTITUDE FOR LEAVING CLOUD
C
  206 KBASE=2
      MD=MC-1
  207 EXTM=(ZLST-CX(MD,3))/(CX(MD,6)-UP+DN)
 1207 DPST(3,MBT)=CX(MD,5)+EXTM*CX(MD,8)
      DPST( 2,MBT)=ZLST+(UP-DN)*EXTM
C
C     IF THE WAFER IS ON THE GROUND, JUMP THE INNER LCCP.  IF NOT,
C     COMPUTE THE POSITION OF THE WAFER BELOW THE CLOCC BASE.
C
      GO TO (1208,233),JBASE
 1208 DPST( 2,MBT)=DPST( 2,MBT)+(CX(MD,6)-DN)*(CX(MD,2)-EXTM)
C
C     COMPUTE BELOW CLOUD AIR DENSITY , VISCOSITY AND TEMPERATURE
C
  208 UP=CX(MC,6)+ZVSB*DPX(2,MC)
      CALL TRPL(OPST( 2,MET),NAT ,ALT,RHO,DEN)
      CALL TRPL(DPST( 2,MBT),NAT ,ALT,ETA,VIS)
      CALL TRPL(DPST( 2,MBT),NAT ,ALT,ATP,TMP)
      GO TO 212
C
G     COMPUTE INSIDE CLOUD GAS DENSITY, VISCOSITY AND TEMPERATURE
C
  210 UP=CX(4C,6)+ZVSB*DPX(1,HC)
      FC=(DPST(1,MBT)-CX(MC,1))/(CX(MC+1,1)-CX(MC,1))
      DEN=CX(MC,10)+(CX(MC+1,10)-CX(MC,10))*FC
      VIS=VISCX(MC)+(VISCX(MC+1)-VISCX(MC))*FC
      TMP=CX( MC,9)+(CX( MC+1,9)-CX( MC,9))*FC
C
C     COMPUTE FALL SPEEDS
C
  212 CALL TRPL(OPST( 2,MET),NAT ,ALT,FRS,P)
      CALL SETTLE(OPST(4,MET),RHOP,OEN,VIS,TMP,P,DN,IACCR)
      IF( ON .LT. SRTHS ) ON = 0.0
      ZNXT=OPST( 2,M8T)+GX(MC,2)*(UP-DN)
C
C     HAS THE PARTICLE REACHED THE GROUND-
C         YES TO 220
C        NO TO 230
C
      IF(ZNXT-ZBRSTZ)220,220,230
C
C     COMPUTE OPST TIME OF ARRIVAL ON FALLOUT FIELD
C
  22C EXTM=(ZBRSTZ-DPST( 2,MBT))/(UP-ON)
      DPST(1,MBT)=DPST(1,MBT)+EXTM
      DPST( 2,MBT)=ZBRSTZ
      DNWAF(MBT)=DN
      JBASE=2
      MD=MC
      GO TO (1207,233),KBASE
  230 DPST(1,MBT)=DPST(1,MBT)+CX(MC,2)
      7LST=OPST(2,MBT)
      DPST(2,MBT)=ZNXT
  238 CONTINUE
  233 GO TO (241,2440),MBT
C
C     IF BOTH TOP AND BOTTOM HAVE BEEN TREATED, ARE THE TOP AND BOTTOM
C     RADII THE SAME---
C        YES TO 5448
C        NO TO 2401
C
  241 IF(ABS(DPST(3,1) - DPST(3,2)) .GT. 0.1) GO TO 2441
 2440 IFLAG=1
      GO TO (240,256),MBT
  240 IF( IC(6) .EQ. 1)
     1WRITE(ISOUT,777)(DPST(I,MBT),I=1,8),MBT,IFLAG
      GO TO 5442
 2441 IFLAG=2
      IF(IC(6))2401,2401,2351
 2351 WRITE(ISOUT,777)(DFS1(I,MBT),I=1,8),MBT,IFLAG
 2401 IF(DPST(2,2)-ZBRSTZ)25(,259,2448
C
C     ADJUST WAFER ALTITUDES IF THEY ARE IMPACTED
C
  259 DPST(2,2)= DPST(2,2) - (CX(MCX,1) - DPST(1,2))*DNWAF(2)
      IF(DPST(2,1) - ZBRSTZ)6020,6020,2448
 6020 OPST(2,1)= OPST(2,1) - (CX(MCX,1) - OPST(1,1))*ONWAF(1)
C     DETERMINE PARAMETERS TO BE USED TO SUBDIVIDE A WAFER WHOSE TOP
C     AND BOTTOM HAVE DIFFERENT RADII
C
 2448 AL=DPST(3,1)/DPST(3,2)
      RB=3.1415927*DPST(3.2)**2
      KDIP=AL
      IF(KDIP-10)2442,2442,2443
 2443 KDIP=10
      GO TO 2444
 2442 IF(KDIP-2)2450,2444,2444
 2450 IF(AL-1.5)2451,2452,2452
 2451 KDIP=1
      GO TO 2444
 2452 KOIP=2
 2444 ZD=DPST(2,1)-DPST(2,2)
      FK=FLOAT(KDIP)
      DZ=ZD/FK
      ALL=0.5*ZD/ALOG(AL)
C
C     SPECIFY PPST ARRAYS FOR THE WAFER SUBDIVISIONS
C
      DO 2445 I=1,KDIP
      FI=FLOAT(I)
      A=DPST(2,2)+(FI-1.)*DZ
      B=A+DZ
      A1=AL**(2.0*(B-DPST(2,2))/ZD)
      A2=AL**(2.0*(A-DPST(2,2))/ZD)
      PPST(2,I)=ALL*(ALOG(0.5*(A1+A2)))+DPST(2,2)
      PPST(3,I)=DPST(3,2)*(AL**((PPST(2,I)-DPST(2,2))/ZD))
      PPST(1,I)=OPST(1,MBT)
      PPST(4,I)=SQRT(DPST(4,1)*DPST(4,2))
      PPST(5,I)=OPST(5,MBT)/FK
      PPST(6,I)=DZ
      PPST(7,I)=A
      PPST(8,I)=RB*ALL*(A1-A2)
C
C     ADJUST PPST ARRAY VALUES FOR AN IMPACTED PARCEL
C
      IF(PPST(2,I).GT.ZBRSTZ) GO TO 3443
      PPST(1,I) = CX(MCX,1) - (ZBRSTZ - PPST(2,I))/(DNWAF(2) +
     1 (DNWAF(1) - DNWAF(2))*(PPST(2,I) - DPST(2,2))/ZD)
      PFST(2,I)=ZBRSTZ
      PPST(6,I)=0.0
      PPST(7,I)=ZBRSTZ
      PPST(8,I)=0.0
      GO TO 2445
 3443 IF(PPST(7,I) .GT. ZBRSTZ) GO TO 2445
      PFST(6,I)=PPST(6,I) - ZBRSTZ + PPST(7,I)
      PPST(8,I)= PPST(8,I) - 3.1415927*(ZBRSTZ- PPST(7,I))*PPST(3,I)**2
      PPST(7,I)=ZBRSTZ
 2445 CONTINUE
 5443 IP=0
 5445 IP=IP+1
C
C     SET UP THE DPST ARRAY FOR A WAFER SUBDIVISION FROM THE PPST ARRAY
C
      00 5444 J=1,8
 5444 OPST(J,MBT)=PPST(J,IP)
 5442 GO TO (5448,5447),IFLAG
C
C     SPECIFY FINAL DPST AFRAY FOR A WAFER WITH EQUAL BASE AND TOP RADIi
C
 5448 DPST(6,MBT)= DPST(2,1)-DPST(2,2)
      DPST(2,MBT)=(DPST(2,1)+DPST(2,2))*0.5
      DPST(4,MBT)=SQRT(DPST(4,1)*DPST(4,2))
      DPST(7,MBT)=DPST(2,2)
      DPST(8,MBT)=DPST(8,MBT)*3.1415927*DPST(3,1)**2
      IF(IC(6))5447,5447,5826
 5826 WRITE(ISOUT,666)(DPST(I,MBT),I=1,8),MBT,IFLAG
 5447 IF(IRAO)5022,5022,783
C
C
C     INITIALIZE FOR HORIZONTAL WAFER SUBDIVISION
C
  783 XR=BZ2
      YR=BZ2
 506C RADIUS=OPST(3,MBT)
      RAD2=RADIUS**2
 5010 IF(RAD2-2.0*8Z2**2)5022,1004,1004
C
C
C
C     SPECIFY GDPST ARRAY FOR WAFERS THAT ARE NOT TO BE SUBDIVIDED
C     HORIZONTALLY
C
 5022 L000=L000+1
      GDPST(6,LODD)=DPST(2,MBT)
      GDPST(4,LODD)=DPST(4,MBT)
      GDPST(3,LODD)=DPST( 1,MBT)
      GDPST(5,LODD)=DPST(5,MBT)
      GDPST(1,LODD)=0.
      GDPST(2,LODD)=0.
      GDPST(7,LODD)=DPST(3,MBT)
      GDPST(8,LODD)=DPST(6,MBT)
      GDPST(9,LODD)=DPST(7,MBT)
      GDPST(10,LODD)=DPST(8,MBT)
      GO TO 5030
 1003 IF((XR)**2+(YR)**2-RAD2)1001,1001,1002
C
C     SUBDIVIDE WAFERS HORIZONTALLY AND SPECIFY THE GCFST ARRAY DATA
C
C
C      COUNT THE TOTAL NUMBER OF HORIZONTAL SUBDIVISIONS
C
 1004 EX=8Z2
      EY=8Z2
      CNT=4.0
 721C EX=EX+8Z
      IF(EX**2+EY**2-RA02)7201,7201,7202
 7201 CNT=CNT+4.0
      GO TO 7210
 7202 EX=BZ2
      EY=EY+BZ
      IF(EX**2+EY**2-RAD2)7201,7201,7203
 7203 CMA=DPST(5,MBT)/CNT
 1C01 L000=L000+1
      LL=L000+3
      DO 1759 J=LODD,LL
      GDPST(9,J)=DPST(7,MBT)
      GDPST(10,J)=DPST(8,YBT)/CNT
      GOPST(7,J)=BZ2
      GDPST（8，J）=DPST（6，MET）
      GDPST(6,J)=DPST(2,MBT)
      GDPST（4，J）=DPST（4，MBT）
      GDPST(3,J)=DPST(1,MBT)
 1050 GOPST(5,J)=CMA
      GDPST(1，LODD)=XR
      GDPST（2，LODD）=YR
      L000=L000+1
      GDPST(1,LODD)=XR
      GDPST(2,LODD)=-YR
      LODD=LODD+1
      GDPST(1,LODD)=-XR
      GDPST(2,L0DD)=-YR
      L000=L000+1
      GDPST(1，LODC)=-XR
      GDPST(2,LODD)=YR
 5030 IF(LODD- 97)1150,1010,1010
 1100 IF(IRAD)2585,2585,1101
 1101 XR=XR+8Z
      GO TO 1003
 1002 YR=YR+8Z
      XR=BZ2
      IF(YR-RADIUS)1063,1003,2585
C
C     LOAD THE GOPST ARRAYS ON THE CRM OUTPUT TAPE
C
 1010 WRITE(IRISE)LOOO
      WRITE(IRISE)(GDPST(1,J),GDPST(2,J),GDPST(3,J),GDPST(4,J),GDPST(5,J
     1),GDPST(6,J),GDPST(7,J),GDPST(8,J),GDPST(9,J),GCPST(10,J),J=1,LODD
     2)
      LODD=0
      GO TO 1130
 2585 GO TO (258 ,2586),IFLAG
 2586 IF(IP-KDIP)5445,258,258
  258 CONTINUE
  278 CONTINUE
C
C     LOAD FINAL RESIDUE CF GDPST DATA ON THE CRM CUTFUT TAPE
C
 1030 WRITE(IRISE)LODD
      WRITE(IRISE)(GDPST(1,J),GDPST(2,J),GDPST(3,J),GDPST(4,J),GDPST(5,J
     1),GDPST(6,J),GDPST(7,J),GDPST(8,J),GDPST(9,J),GCPST(10,J),J=1,LOCD
     21
      LOOD=C
      WRITE(IRISE)LODD
      ENO FILE IRISE
      FEWIND IRISE
      RETURN
      END
