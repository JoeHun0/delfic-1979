      END FILE JPARN
      REWIND JPARN
      REWIND IRISE
      RETURN
 7734 CALL ERROR(PROGRM,IRROR,ISOUT)
      RETURN
C
C 103 READ A BLOCK OF N PARTICLE DESCRIPTIONS
  103 READ(IRISE )(XPAR(J),YPAR(J),TP(J),PSIZ(J),PMAS(J),ZPAR(J),RWAF(J)
     1,DWAF(J),ZLOW(J),VWAF(J),J=1,N)
      IF(IC(7))2015,2010,2015
 2015 WRITE(ISOUT,3013)N
      WRITE(ISOUT,1012)(XPAR(I),YPAR(I),TP(I),PSIZ(I),PMAS(I),ZPAR(I),
     1RWAF(I),OWAF(I),ZLCW(I),VWAF(I),I=1,N)
