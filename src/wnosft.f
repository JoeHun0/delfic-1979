C     FETCH THE NEXT BLOCK OF FARTICLE DATA.
      J=J+1
      IF(J-N)105,105,110
C
C 110 PUT THE MODIFIED DATA ON THE TAPE JPAPIN AND THEN RETURN TO
C     FETCH THE NEXT DATA BLOCK.
  113 WRITE(JPARN )N
      WRITE (JPARN )(XPAR(J),YFAR(J),ZFAR(J),TF(J),PSIZ(J),PMAS(J),RWAF
     1(J),DWAF(J),ZLOW(J),VWAF(J),J=1,N)
      IF(IC(7))185,104,185
  185 WRITE (ISCUT,4)N
      WRITE(ISOUT,3)(XPAR(I),YPAR(I),TF(I),PSIZ(I),PMAS(I),ZPAR(I),
     1RWAF(I),DWAF(I),ZLCH(I),VWAF(I),I=1,N)
  190 GO TO 104
 106  OLDPS=PSIZ(J)
      OLDZ=ZPAR(J)
      OLDT=TP(J)
