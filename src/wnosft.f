C 114 THE PARTICLE HAS LEFT THE CLOUD
C
  114 ZCUR=ZPAR(J)
      IF( ZCUR .LT. ZBRSTZ ) ZCUR=ZBRSTZ
      TCUR=TP(J)
      DX=0.
      DY=0.
