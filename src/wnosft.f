  124 DELT=TC(K+1)-TTEMP
      TTEMP=TC(K+1)
      ZTEMP=ZC(K+1)
      XC(K+1)=XT+VX(J)*DELT
      YC(K+1)=YT+VY(J)*DELT
      XT=XC(K+1)
      YT=YC(K+1)
      K=K+1
      IF(K- MCX ) 122,125,125
C
C 125 CLOUD TFAJECTORY IS COMPLETE
  125 WRITE(ISOUT,6022)
      WRITE (ISOUT,2)(XC(J),YC(J),ZC(J),TC(J),VC(J),J=1,MCX)
C
  104 READ(IRISE)N
      IF(N)102,102,103
C
C 102 FINAL EXIT.   ALL DATA HAVE BEEN MODIFIED.  MARK JPARIN COMPLETED.
 102  N=0
      IF(IC(7))2013,2014,2013
 2C13 WRITE(ISOUT,3013)N
