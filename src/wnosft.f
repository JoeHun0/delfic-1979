C     XPAR(I)    ADJUSTED X COORDINATE OF PARCEL (M)
C     YC(I)      Y COORDINATE OF THE CLOUD CAP CENTER FOR THE ITH CLOUD
C                RISE TABLE ENTRY AFTER WIND SHIFT ACJUSTMENT
C     YPAR(I)    ADJUSTED Y COORDINATE OF PARCEL (M)
C     ZB(I)      CLOUD  BASE  ALT.  OF THE I-TH CLOUD RISE TABLE ENTRY
C                (METERS ABOVE MSL)
C     ZC(I)      CLOUD CENTER ALT.  OF THE I-TH CLOUD RISE TABLE ENTRY
C                (METERS ABOVE MSL)
C     ZCUR       PARCEL   ALTITUDE AT THE BEGINNING CF A WIND DRIFT
C                ADJUSTMENT CALCULATION INCREMENT
C     ZLOW(I)    ALTITUDE CF PARCEL BASE (M)
C     ZPAR(I)    Z COORDINATE OF PARCEL (M ABOVE MSL)
