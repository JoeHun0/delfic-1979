      SUBROUTINE WNDSFT
C
C     H. G. NORMENT, ATMOSPHERIC SCIENCE ASSOCIATES - DECEMBER 1978
C
C
C     THIS PROGRAM READS A TAPE ( IRISE) OF DATA WHICH DESCRIBES AN
C     AXIALLY SYMMETRIC STABILIZED CLOUD OF FALLCUT PARCELS
C     AND TRANSLATES THE HORIZONTAL COORDINATES OF EACH PARCEL
C     TO ACCOUNT FOR WINC CRIFT DURING THE CLOUD RISE TIME INTERVAL.
C     IT ALSO APPLIES A TRANSLATION OF GZ COORDINATES AND TIME.
C     RESULT IS WRITTEN ONTO TAPE JPARN FOR USE BY THE TRANSPORT MODULE.
C
C ******************** GLOSSARY ********************
C
C     DWAF(I)    PARCEL VERTICAL DIMENSION (M)
C     DX         WIND-SHIFT CORRECTION TO BE ADDED TO THE PARCEL X
C                COORDINATE
C     DY         WIND-SHIFT CORRECTION TO BE ACDED TO THE PARCEL Y
C                COORDINATE
C     FV         STILL AIR PARTICLE SETTLING RATE
C     IRROR      NUMBER OF STATEMENT NEAR WHERE AN ERROR WAS DISCOVERED
C     PMAS(I)    TOTAL PARTICULATE MASS (KGM) OF PARCEL
C     RV         UPWARD COMPONENT OF VELOCITY CF A STEM PARCEL
C     RWAF(I)    RAJIUS (METERS) OF PARCEL AT CENTER CF MASS
C     TC(I)      TIME(RELATIVE TO CETONATION OF)THE I-TH CLOUD RISE
C                TABLE ENTRY
C     TCUR       PARCEL   TIME COORDINATE DURING A WIND DRIFT
C                ADJUSTMENT CALCULATION INCREMENT
C     TP(I)      TIME OF DEFINITION (SEC) OF THE I TH PARCEL
C     VB(I)      CLOUD  BASE  VEL.  OF THE I-TH CLOUD RISE TABLE ENTRY
C     VC(I)      VELOCITY ASSOCIATED WITH CLOUD AT ZC(I) AT TC(I).
