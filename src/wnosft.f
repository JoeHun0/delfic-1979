     4), (DWAF(1),GDPST(701)), (ZLOW(1),GDPST(801)),(VWAF(1),GDPST(901))
     5,(XC(1),CX(1,2)),(YC(1),CX(1,8)),(ZC(1),CX(1,9)),(VC(1),CX(1,10))
