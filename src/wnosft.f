      CALL TRPL(ZCUR,NAT,ALT,ATP,T)
      CALL TRPL(ZCUR,NAT,ALT,PRS,P)
      CALL TRPL(ZCUR,NAT,ALT,RHO,DEN)
      CALL TRPL(ZCUR,NAT,ALT,ETA,VIS)
C
C     LOCATE PARTICLE DEFINITION TIME IN THE CLOUD RISE TABLE.
C
      00 210 K=1,MCX
      LL=MCXP1-K
      IF(TC(LL).LE.TP(J)) GO TO 221
  210 CONTINUE
  211 IRROR=-211
      GO TO 7734
