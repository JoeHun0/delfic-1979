C     PELATIVE TO CUORCINATE SYSTEM ORIGIN
  108 TP(J)=TP(J)+TGZ
 109  XPAR(J)=XPAR(J)+DX+XGZ
      YPAR(J)=YPAR(J)+DY+YGZ
