      SUBROUTINE ICRMEX(NUMTAP)
C
C     H. G. NORMENT. ATMOSPHERIC SCIENCE ASSOCIATES - DECEMBER 1976
C
C
C                  INITIALIZATION AND CLOUD RISE MODULE
C
C     DETERMINES INITIAL VALUES OF -
C     TIME, TEMPERATURE, TCTAL SOIL MASS, FRACTION OF THE SOIL BURDEN IN
C     THE VAPOR PHASE, AND THE SIZE FREQUENCY DISTRIBUTION OF THE
C     FALLOUT PARTICLES.  NEXT IT PERFCRMS A DYNAMIC CLOUD RISE AND
C     STABILIZATION SIMULATION.  THEN IT ESTABLISHES AN
C     AXISYMMETRIC DISTRIBUTION OF FALLOUT PARCELS ABOVE GZ.   FINALLY
C     THE COORDINATES OF THESE PARCELS ARE ADJUSTED TO ACCOUNT FOR
C     WIND TRANSPORT DURING THE PERIOD OF CLOUD RISE AND STABILIZATION
C     AND A TRANSLATION OF THE COORDINATES OF GZ AND  LETONATION TIME.
C
C ******************** GLOSSARY ********************.
C
C  ALT    - ARRAY(256), ATMOSPHERE ALTITUDE IN METERS(MSL) CORRESPONDING
C           TO ATP, PRS, RLH, RHO, ETA
C  ATMR   - SUBROUTINE, READS IN TABLES OF ALT,ATP,PKS,RLH,KHO,ETA
C  ATID   - ARRAY(12), 72 ALPHANUMERIC CHARACTERS FOR ATMOSPHERE IDENT.
C  ATP    - ARRAY(256), ATMOSPHERE TEMPERATURE (K) MATCHES ALT
C  BARMU  - MEDIAN DIAMETER OF THE LOGNORMAL PARTICLE SIZE VS. VOLUME
C           DISTRIBUTION (MICROMETERS)
C  82     - DEPOSIT INCREMENT LINEAR DIMENSION(CX(5,MCX)/IRAD)
C  CAYM   -  K-TO-MASS RATIO PARAMETER OF THE POWER-LAW PARTICLE DISTBN.
C  CG     - ARRAY(200), FALLING SPEEDS OF PARTICLES IN THE CLOUD (M/SEC)
C  CHANGE - CLOUD TIME AFTER WHICH STEP LENGTH CHANGES TO DST2
C  CL     - LATENT HEAT OF VAPORIZATION OF WATER
C  CMLR   - CLOUD MASS LOSS RATE OF PARTICULATE FALLOUT
C  CP     - SPECIFIC HEAT OF AIR
C  CPAI   - SPECIFIC HEAT OF AIR INTEGRATED FROM TE TO T
C  CPFP   - SUBROUTINE, COMPUTES PARTICLE FALLCUT RATE DURING CLOUD
C           RISE CALCULATIONS
C  CR     - WEIGHTED AVERAGE SPECIFIC HEAT FOR AIR AND SOIL
C  CRM    S UBROUTINE,C OMPUTESD YNAMICC LOUDR ISEA NDE XPAN SION
C  CRMINT - SUBROUTINE, COMPUTES INITIAL CRM VARIABLES
C  CRMW   - SUBROUTINE, PRINTS CRM OUTPUT
C  CX     - ARRAY(50,10), CLOUD PROPERTIES VS. TIME COMPILED DURING CRM
C           CALCULATIONS AND USED BY RSXP AND WNDSFT
C           (J,1) = TIME(SEC) AFTER BURST
C           (J,2) - CLOUD TIME INTERVAL(SEC) BEGINNING AT CX(J,1)
C           (J,3) - CLOUD BASE(M) AT CX(J,1)
C           (J,4) - CLOUD TOP(H) AT CX(J,1)
C           (J,5) - CLOUD RADIUS(M) AT CX(J,1)
C           (J,6) - CLOUD EASE RATE (M/SEC) DURING CX(J,2)
C           (J,7) - CLOUD TOP  RATE (M/SEC) CURING CX(J,2)
C           (J,8) - CLOUD RADIAL RATE(M/SEC) DURING CX(J,2)
C           (J,9) - CLCUD TEMPERATURE (K) AT CX(J,1)
C           (J,10) - IN-CLCUD GAS DENSITY (KG/M**3) AT CX(J,1)
C  CXPN   - SUBROUTINE, TABULATES CX ARRAY
C  C2     - CONSTANT USED IN EDDY VISCOSITY MOMENTUM GENERATION
C           (YIELD DEPENCENT)
C  C3     - CONSTANT USED IN COMPUTING TURBULENT ENERGY DISSIPATION RATE
C  C6     - CONSTANT USED IN COMPUTING AIR ENTRAINMENT RATE INTO CLOUD
C           CAUSED BY WIND SHEAR
C  DEK    - DERIVATIVE OF EK
C  DMEAN  - MEDIAN DIAMETER (MICROMETERS) OF A LCGNORMAL PARTICLE
C           SISE DISTRIBUTION
C  DERIV  - SUBROUTINE, EVALUATES DERIVATIVES OF CLOUD PROPERTIES
C  DETID  - ARRAY(12), 72 ALPHANUMERIC DETONATION IDENTIFICATION
C  DIAM   - ARRAY(201), UPPER BOUNDARY OF I-TH PARTICLE SIZE CLASS.
C           THE LAST ENTRY IN THE ARRAY IS THE LOWER BOUNDARY OF THE
C           LAST(SMALLEST) PARTICLE SIZE CLASS. THE LENGTH OF THE DIAM
C           ARRAY IS ALWAYS ONE GREATER THAN THE NUMBER OF SIZE CLASSES.
C           (METERS)
C  DNS    - FALLOUT PARTICLE DENSITY (GM/CM**3), DEFAULT VALUE IS 2.6
C  DPST   - ARRAY(8,2),    FALLOUT PARCEL  VARIABLES COMPILED IN
C           SUBROUTINE RSXP. THE SECOND INDEX IS NEEDED ONLY IN THE RSXP
C           CALCULATIONS TC DISTINGUISH THE PARCEL TOP FROM BASE
C           (1,MBT) - TIME  (SEC) OF ALTITUDE STABILIZATION OR GROUNDING
C           (2,MBT) - ALTITUDE OF  PARCEL   CENTER OF MASS (METERS)
C           (3,MBT) - PARCEL    RADIUS AT CENTER OF MASS (METERS)
C           (4,M3T) - MEAN PARTICLE DIAMETER  (METERS)
C           (5,MBT) - PARCEL MASS (KG) FOR A SIZE-MASS FRACTION PARTICLE
C                     DISTRIBUTION
C                     PARCEL ACTIVITY FRACTION FOR A SIZE-ACTIVITY
C                     FRACTION PARTICLE DISTRIBUTION
C           (6,MBT) - PARCEL    VERTICAL THICKNESS (METERS)
C           (7,MBT) - ALTITUDE OF PARCEL BASE (METERS)
C           (8,MBT) - PARCEL    VOLUME  (CUBIC METERS)
C  DPSTK  - NUMBER OF  FALLOUT PARCELS   PER PARTICLE SIZE CLASS
C  DPX    - ARRAY(2,90),  FALLOUT PARCEL   RISE AND EXPANSION VARIABLE
C           (1,J) - LIFT RATE FACTOR ABOVE CLOUD BASE (1/SEC)
C           (2,J) - LIFT RATE FACTOR BELOW CLOUD BASE (1/SEC)
C  DRM    - DERIVATIVE OF RM
C  DS     - DERIVATIVE OF S
C  DST    - INTEGRATION TIME STEP
C  DSTO   - INITIAL INTEGRATION TIME STEP
C  DST1   - INTERMEDIATE INTEGRATION TIME STEP
C  DST2   - FINAL VALUE OF INTEGRATION TIME STEP
C  OT     - DERIVATIVE OF 1
C  DU     - DERIVATIVE OF L
C  DV3L   - ARRAY(8), USED TO TRANSMIT VARIABLE DERIVATIVES TO RKGILL
C  DWT    - DERIVATIVE OF WT
C  DY     - DERIVATIVE OF X
C  07     - DERIVATIVE OF Z
C  ED     - EDDY VISCOSITY LOSS RATE OF KINETIC ENERGY OF RISE
C  EK     - TURBULENT KINETIC ENERGY DENSITY
C  EPS    - KINETIC ENERGY LOSS RATE
C  ERROR  - SUBROUTINE, FOR GENERAL UTILITY ERROR INDICATION
C  ES     - SATURATION PRESSURE OF WATER VAPOR (INVALID FOR TEMPERATURE
C           ABOVE BOILING POINT OF WATER)
C  ETA    - ARRAY(256), ATMOSPHERIC DYNAMIC VISCOSITY  (COEFF. OF VISC.)
C           (KGM/(M-SEC)) PATCHES ALT ARRAY
C  EXTM   - IN SUBROUTINE RSXP, TIME INCREMENT BETWEEN WAFER HISTORY
C           DESCRIPTION POINTS
C F - FRACTION OF W IN FIREBALL AT START OF RISE
C  FMASS  - ARRAY(200),PARTICLE SIZE CLASS FRACTION OF TOTAL MASS OR
CACTIVITY LIFTEC BY THE CLOUD
C  FMT    - OBJECT TIME FORMAT USED TO READ CATA
C  FCRM   - DESIGNATES WHETHER WIND VELOCITIES ARE RESOLVED OR INPOL AR
C           (METEOROLOGICAL CONVENTION) FORM
C  FH  -  FISSION  YIELD  IN  KILOTONS
C  GOPST  - ARRAY(10,100),   FALLOUT PARCEL  VARIAELES (OUTPUT OF RSXP)
C           (1,J) - FALLOUT PARCEL    X COORDINATE (METERS)
C           (2,J) - FALLOUT PARCEL    Y COORDINATE (METERS)
C           (3,J) - TIME C(ORDINATE (SEC)
C           (4,J) - PARTICLE DIAMETER (METERS)
C           (5,J) - PARCEL MASS (KG) FOR A SIZE-MASS FRACTION PARTICLE
C                   DISTRIBUTION
C                   PARCEL ACTIVITY FRACTION FOR A SIZE-ACTIVITY
C                   FRACTICN PARTICLE DISTRIBUTION
C          (6,J) - Z COCRICINATE OF PARCEL CENTER CF MASS (METERS)
C           (7,J) - PARCEL    RADIUS AT CENTER OF MASS (METERS)
C           (8,J) - PARCEL    VERTICAL THICKNESS (METERS)
C           (9,J) - ALTITUDE OF PARCEL BASE (METERS)
C           (10,J) - PARCEL    VOLUME (CUBIC METERS)
C  HEIGHT - HEIGHT OF BURST (METERS) ABOVE GROUND ZERO
C           (FOR A SUBSURFACE BURST INPUT A NEGATIVE VALUE)
C  HLR    - RELATIVE HUMIDITY AT ALTITUDE OF CLOUD CENTER
C  HOB    - HEIGHT(FT) OF BURST ABOVE GROUND ZERO
C  IRAD   - NUMBER OF CLOUE DISC  RADIUS SUBDIVISIONS (SEE BZ)
C  IRISE  - LOGICAL DESIGNATION FOR TAPE USED FOR TEMFORY STORAGE IN
C           ATHR AND FOR RSXP OUTPUT
C  ISIN   - INPUT TAPE
C  ISOUT  - OUTPUT TAPE
C  JBASE  - COMPUTED GO TO INDEX USED IN SUBROUTINE RSXP
C           1 - CONTINUE OPST TRAJECTORY COMPUTATION
C           2 - DPST TRAJECTORY COMPUTATION COMPLETE
C  JPARN  - BINARY OUTPUT TAPE, SUBROUTINE WNDSFT
C  KBASE  - COMPUTED GO TO INDEX USED IN SUBROUTINE RSXP
1           . - ADJUST OFST RADIUS AND ACTIVITY FOR LEAVING CLOUD
C           2 - ADJUSTMENT OF 1 HAS BEEN MADE
C  KCX    - NUMBER OF DPST RISE AND EXPANSION INTERVALS
C  KDI    - NUMBER OF VERTICAL CLOUD SUBDIVISIONS PER PARTICLE SIZE CLAS
C           IF NOT PUNCHEC, IT IS COMPUTED IN ICM
C  K[IP   - IN SUBROUTINE RSXP, NUMBER OF VERTICAL SUBDIVISIONS OF A
C           PARCEL WHOSE TGP AND BASE RADII ARE NOT EQUAL
C  KDPST  - SEE DPSTK
C  KSV    - INDEX WHICH DETERMINES FUNCTION OF SUBROUTINE RSTR
C           1 - PRESERVE VARIABLES AT START OF TIME STEP
C           2 - RESTORE VARIABLES TO THOSE AT START OF TIME STEP
C  LODO   - LENGTH OF PARCEL   DESCRIPTION DATA PLUCK (GDPST ARRAY IN
C           RSXP)
C  MBT    - IN SUBROUTINE RSXP, DISTINGUISHES A PARCEL TOP FROM BASE
C           MBT=1 SPECIFIES A PARCEL TCP
C           M8T=2 SPECIFIES A PARCEL BASE
C  MCX    - NUMBER OF TIME POINTS (COLUMNS) OF CX ARRAY
C  MWYA   - 1, INITIAL ENTRY INTO CXPN
C           2. REGULAR ENTRY
C           3, FINAL ENTRY
C  N      - CLOUD MODE SWITCH
C  NAT    * NUMBER OF ELEMENTS IN ALT AND CORRESPONDING ARRAYS
C           LIMITS OF NAT = 1,256
C  NOSTR  - NUMBER OF ENTRIES IN PARTICLE SIZE CLASS TABLE
C  NH000  - NUMBER OF ENTRIES IN THE WIND PROFILE TABLE
C  P      - ATMOSPHERIC PRESSURE AT CLOUD CENTER ALTITUDE (PASCALS)
C  PHI    - FRACTION OF F*W USED TO HEAT AIR AND SCIL AT THE INITIAL
C           TIME.  THE REMAINDER IS USED TO HEAT WATER
C  PPST   - ARRAY(8,10), TEMPORARY STORAGE OF FARCEL VARIABLES IN RSXP
C  PRS    - ARRAY(256) ATMOSPHERIC PRESSURE (PASCALS) MATCHES ALT
C  PS     - ARRAY(200), PARTICLE SIZE CLASS MIDPOINT DIAMETER (METERS)
C  PW     - PARTIAL PRESSURE OF WATER VAPOR IN THE CLCUD
C  Q      - CONVERSION FACTOR FOR FRACTION MASS TO NUMBER OF PARTICLES
C PER 3
C  QX     - FACTOR CONVERTS CLOUD TEMPERATURE TO VIRTUAL CLOUD
C           TEMPERATURE
C  QXE    - INVERSE OF FACTOR TO CONVERT AMBIENT TEMPERATURE TO
C           VIRTUAL AMBIENT TEMPERATURE
C  R      - CLOUD HORIZONTAL RADIUS
C  RA     - GAS DENSITY OF CLOUD
C  RADC   - PI/180,  CONVERTS DEGREES TO RADIANS
C  RADIUS - FALLOUT  PARCEL   RADIUS USED IN SUBROUTINE RSXP
C  RHO    - ARRAY(256)  ATMOSPHERE AIR DENSITY (KGM/M**3) MATCHES ALT.
C  RHOP   - FALLCUT PARTICLE DENSITY (KG/M**3)
C  RKGILL - SUBROUTINE, RUNGE-KUTTA-GILL INTEGRATION
C  RL     - ENTRAINMENT PARAMETER
C  RLH    - ARRAY(256)  ATMOSPHERE RELATIVE HUMIDITY MATCHES ALT(PERCENT
C  RM     - CLOUD MASS
C  RMAO   - INITIAL AIR MASS IN CLOUD
C  RMWO   - INITIAL WATER PASS IN CLOUD
C  RSTR   - SUBROUTINE WHICH PRESERVES AND/OR PESTORES CRM VARIABLES
C  RSXP   - SUBROUTINE, ESTABLISHES FALLOUT PARCEL POSITIONS IN SPACE
C           ABOVE GZ AT STABTLIZATION TIME.
C  RZT    - VERTICAL CLOUD RADIUS
C  S      - CONDENSED SOIL MIXING RATIO
C  SD     - GEOMETRIC STANDARD DEVIATION FOR A LCGNORMAL PARTICLE SIZE
C           DISTRIBUTION (SET EQUAL TO 4.0 IF NOT INPUT) (DIMENSIONLESS)
C           FOR A SIZE-ACTIVITY PARTICLE DISTBN. THE CCDE SETS SD=-1.0
C  EXPO   - EXPONENTIAL PARAMETER OF THE POWER-LAW PARTICLE DISTBN.
C  SHAPE  - EQUAL TO RZT/R.  A CONSTANT USED TO COMPUTE CLOUD SHAPE
C           WHEN U .GT. 0.0
C  SHWIND - SUBROUTINE, READS SHOT-TIME WIND DATA
C  SLOTMP - PARTICLE SOLIDIFICATION TEMPERATURE (K) DEFAULT VALUE 2200.
C  SMALLT - TIME AFTER START OF COMPUTATION
G  SOILHT - LATENT HEAT CF VAPORIZATION OF CLOUD SOIL CONSTITUENT
C  SSAM   - TOTAL MASS (KG) OF SOIL (OR WEAPON DEBRIS FOR AN AIRBURST)
C           IN THE CLOUD AT THE INITIAL TIME
C  T      - CLOUD TEMPERATURE (K)
C  TE     - ATMOSPHERIC TEMPERATURE AT CLOUD CENTER ALTITUDE (K)
C  TGZ    - TIME (SEC) OF CETONATION
C  TME      TIME (SEC) OF INITIAL CONDITIONS SPECIFICATION RELATIVE TO
C           DETONATION.
C  TMPG   - INITIAL VAPOR TEMPERATURE (K)
C  TMPS   - INITIAL TEMPERATURE OF CONCENSED PHASE MATERIAL IN CLOUD (K)
C  TMSO   - TIME OF PARTICLE SOLIDIFICATION (SEC) WITHIN CLOUD
C  TRPL   - SUBROUTINE, LINEAR INTERPOLATION
C  TSRD   - R-RATE CLOUD RISE TERMINATION SWITCH PARAMETER
C     TSTM   - TIME AT WHICH NEXT CX ARRAY ENTRIES ARE TO BE MADE
C     T2M    - TIME (SEC) OF THE FIREBALL SECOND TEMPERATURE MAXIMUM
C  U      - CLOUD VERTICAL VELOCITY
C  V      - CLOUD VOLUME
C     VBL    - ARRAY(8), DUMMY VARIABLES OF INTEGRATION(SUBS. DERIV,RKGI
C     VIS    - DYNAMIC VISCOSITY (KG/(M-SEC))
C     VPR    - MASS OF FALLOUT VAPOR (KG) AT THE INITIAL TIME
C     VX(I)  - ARRAY(100), X-COMPONENT OF WIND VELOCITY AT WIND PROFILE
C           STRATUM I, (METERS/SEC)
C     VY(I)  - ARRAY(100), Y-COMPONENT OF WIND VELOCITY AT WIND PROFILE
C           STRATUM I, (METERS/SEC)
C  W      - TOTAL YIELD (KT)
C     WNDSFT - SUBROUTINE, ADJUSTS FALLOUT PARCEL COORDINATES FOR WIND
C           TRANSPORT DURING RISE AND EXPANSION AND FOR COORDINATE
C           TRANSLATION.
C  WT     - SOLID AND LIQUID WATER MIXING RATIO
C  X      - IN-CLOUD WATER VAPOR MIXING RATIO
C  XE     - AMBIENT AIR WATER VAPOR MIXING RATIO
C  XGZ    - X COORDINATE OF GROUND ZERO (METERS)
C  Y      - ARRAY(200),NUMBER OF IN-CLOUD PARTICLES/UNIT VOLUME OF CLOUD
C  YGZ    - Y COORDINATE OF GROUND ZERO (METERS)
C  Z      - CLOUD CENTER ALTITUDE (METERS)
C  ZBFR   - MAXIMUM Z OF CURRENT OR PREVIOUS ENTRIES TABULATED BY CXPN
C  ZBRSTZ - Z-COORDINATE CF BURST GROUND ZERO (METERS ABOVE MSL)
C  ZLMT   - UPPER LIMIT FOR CLOUD CENTER ALTITUDE TO PREVENT POSSIBLE
C           COMPUTATIONAL FUNAWAY
C  ZSCL   - SCALED HEIGHT CF BURST (FT/(KT)**(1.0/3.4))
C  ZV(I)  - ALTITUDE OF CENTER PLANE OF WIND PROFILE STRATUM I (M MSL)
C  ZVSB   - IN SUBROUTINE RSXP, DISTANCE OF A FARCEL ABOVE CLOUD BASE
C
C
      COMMON /BASIC/ W,FH,ZBRSTZ,HEIGHT,ZSCL,SLOTMF,TMSD,XGZ,YGZ,TGZ
      COMMON /CONTRL/ DETIO(12),IC(20),IRAD,IRISE,ISIN,ISOUT,JPARN,KOI
      COMMON /TABLES/ MCX, CX(50,10), GDPST(10,100)
C
      DIMENSION CXTIM(50),CXTMP(50),NUMTAP(15)
      EQUIVALENCE (CXTIM(1),GDPST(601)), (CXTMP(1),GOFST(651))
C
C
COPY IN BASIC AND CONTROL DATA, ESTABLISH CONDITIONS IN THE FIREBALL AT
C     INITIALIZATION TIME, SET UP FALLOUT PARTICLE SIZE DISTRIBUTION
C     TABLES AND PRINT HEADINGS AND DATA.
      ISIN =NUMTAP( 1)
      ISOUT=NUMTAP( 2)
      CALL ICM
      IF(IC(3) .NE. 0) RETURN
      IRISE=NUMTAP( 3)
      JPARN=NUMTAP( 4)
COPY IN ATMOSPHERE DATA
      CALL ATMR
COPY IN SHOT-TIME WIND DATA
      CALL SHWIND
COMPUTE INITIAL VALUES FOR THE CLOUD RISE EQUATIONS
      CALL CRMINT
COMPUTE THE DYNAMIC CLOUD RISE
      CALL CRM
COMPUTE TIME OF FALLOUT SOLICIFICATION
      00 122 MA=1.MCX
      MB=MCX-MA+1
      CXTIM(MA)=CX(MB,1)
  122 CXTMP(MA)=CX(MB,9)
      CALL TRPL(SLOYMP,MCX,CXTMP,CXTIM,TMSO)
      WRITE(ISOUT,513)SLDTMP,TMSD
  513 FORMAT( //////10X,42HTIM EO FSOI LSOLIDIFICATIONAT TEMPERATUREF10.
     14,  8H DEG. ISF9.4, 5H SEC.)
COMPUTE FALLOUT PARCEL DISTRIBUTION IN SPACE ABOVE GZ AT STABLIZATION
      CALL RSXP
COMPUTE WIND-ADJUSTED FALLOUT PARCEL COORDINATES AND TRANSLATE GZ AND
C     DETONATION TIME COCRCINATES.  WRITE BINARY OUTPUT TAPE.
      CALL WNDSFT
      RETURN
      END
