      SUBROUTINE VAPOR
C
C     H. G. NORMENT, ATMOSPHERIC SCIENCE ASSOCIATES - DECEMBER 1978
C
C
C     ESTIMATES PORTION OF FALLOUT MASS (CALC. BY SR MASS) IN THE
C     VAPOR STATE AT THE INITIAL TIME
C
C
      COMMON /BASIC/ W.FW,ZBRSTZ,HEIGHT,ZSCL,SLOTMP,TMSD,XGZ,YGZ,TGZ
      COMMON /CONTRL/ DETIO(12),IC(20),IRAD,IRISE,ISIN,ISOUT,JPARN,KDI
      COMMON /INITL/ F, PHI, SSAM, TME, TMPG, TMPS, VPR
C
C
C     BRANCH ON THE  BASI SO FSOI LCATEGOR   Y-SILICOUS TO 100,
C     CALCAREOUS TO 200
      IF(IC(2))100,100,200
C
C     IS THE COMPUTED VAPCR TEMPERATURE HIGHER THAN THE SILICEOUS SOIL
C     BOILING TEMPERATURE
 100  IF(TMPG-3000.0)120,120,110
 110  VPR=SSAY*0.00015*(TMPG-3000.0)
      GO TO 133
C
C     IS THE COMPUTED VAPCR TEMPERATURE HIGHER THAN THE CALCAREOUS SOIL
C     BOILING TEMPERATURE
 200  IF(TMPG-3100.0)120,120,115
 115  VPR=SSAM*0.00015*(TMFG-310J.0)
      GO TO 130
 120  VPR=1.0
 130  RETURN
      END
