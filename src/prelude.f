-DECK,TRPL
      SUBROUTINE TRPL (
     1  ARG, NPR, PARA, PARB, VRB)
C
C
C     TRPL USES LINEAR INTERPOLATION TO LOCATE POSITION OF ARG WITHIN
C     THE ONE-DIMENSIONAL ARRAY PARA AND COMPUTES FOR THE CORRESPONDING
C     POSITION IN THE ONE-DIMENSIONAL ARRAY PARB, VKB. NPK IS THE
C     DIMENSION OF PARA AND PARB (WHOSE ELEMENTS CORRESPOND ONE TO ONE).
C     IF ARG IS OUTSIDE THE TABULATED VALUES OF PARA, VRB IS SELECTED
C     FROM THE CORRESPONDING END OF PARB.
C     PARA IS ORDERED FROM LEAST (PARA (1)) TO GREATEST (PARA (NPR))
C
C
      DIMENSION
     1  PARA ( NPR), PARB (NPR)
C
C\sim
  020 IF (ARG - PARA (1)) 022, 022, 040
  C22 MB = 1
  024 VRB = PARB (MB)
  L26 RETURN
  640 00 054 MA =2, NPR.
      IF (ARG - PARA (MA)) 048, 044, 054
  C44 MB = N1
      GO TO 024
  048 VRB = (ARG - PARA (MA - 1)) * (PARB (MA) - PARB (MA - 1)) /
     1  (PARA (MA) - PARA (MA - 1)) + PARB (MA - 1)
      GO TO 026
  L54 CONTINUE
      MB = NPR
      GO TO 024
      END
